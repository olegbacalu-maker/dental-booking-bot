/**
 * Шрифт — к первому кадру содержимого, а не после него (03.10, стенд shift_sweep).
 *
 * Inter вшит файлами по подмножествам (`fonts.css`, `font-display:swap`), и
 * браузер просит файл, только когда раскладка встретила текст из его
 * диапазона. До приезда файла текст разложен ЗАПАСНЫМ шрифтом с другими
 * ширинами, а приезд раскладывает его заново. На «Securitate» ответ
 * `/api/settings/security` (8 мс) обгонял шрифт, и подсказка внизу экрана
 * переносила строку уже на кадре с данными: сдвиг 0,0318 через 42 мс после
 * первого кадра содержимого, в одном прогоне из трёх. С шрифтом, задержанным
 * на сервере, тот же сдвиг был в КАЖДОМ прогоне, и ещё на двух экранах.
 *
 * ⭐ Отсюда правило загрузчика экрана (`routeLoader`): данные уходят роутеру,
 * когда для них готов шрифт, и кадр содержимого сразу окончательный. Голова
 * документа просит те же файлы заранее (`layout._doc_head`, preload), поэтому
 * обычно ждать уже нечего — ожидание держит гарантию, когда сеть медленнее.
 */

/**
 * Буквы самого интерфейса. Он румынский, и его диакритика (ă, ș, ț) живёт в
 * подмножестве latin-ext — его экран просит всегда, даже когда в данных нет
 * ни одной такой буквы. Остальное (кириллицу русских имён) скажут данные.
 */
const UI_TEXT = 'Aa ĂăÂâÎîȘșȚț'

/**
 * Дольше не ждём. Шрифт, не приехавший за секунду, превратил бы «сдвиг» в
 * зависание экрана; тогда кадр рисуется запасным шрифтом — ровно то, что
 * `font-display:swap` делал и без ожидания.
 */
export const FONT_WAIT_MS = 1000

/**
 * Дождаться файлов шрифта, нужных этому тексту (данным экрана) и буквам
 * интерфейса. Семейство — то, которым пишет `body` (`--font` темы): у
 * системного шрифта в `document.fonts` лиц нет, и ждать нечего.
 * ⛔ Не отклоняется никогда: шрифт — оформление, и его отказ не имеет права
 * стать отказом экрана.
 */
export function fontsFor(text: string, cap: number = FONT_WAIT_MS): Promise<void> {
  /* jsdom и старые движки FontFaceSet не знают — кадр не ждёт ничего. */
  const fonts = document.fonts as FontFaceSet | undefined
  if (!fonts || !document.body) return Promise.resolve()
  let wait: Promise<unknown>
  try {
    wait = fonts.load(`1em ${getComputedStyle(document.body).fontFamily}`, UI_TEXT + text)
  } catch {
    return Promise.resolve()
  }
  return new Promise<void>((done) => {
    const timer = setTimeout(done, cap)
    void wait.catch(() => undefined).then(() => {
      clearTimeout(timer)
      done()
    })
  })
}
