import { afterEach, describe, expect, it } from 'vitest'
import { freshOf, readSeen, seenKey, writeSeen } from './fresh'

/* Память дня и разница двух конвертов — правило без единого узла DOM.

   ⛔ «Свежее» здесь значит «этого номера не было в прошлом снимке», и ничего
   больше: ни отметки времени, ни поля от сервера. Так считает легаси, и
   память у них ОБЩАЯ — тот же ключ в том же хранилище. */

afterEach(() => sessionStorage.clear())

describe('C26.5.4: что считается приехавшим', () => {
  it('⛔ первый показ дня не подсвечивает НИЧЕГО', () => {
    /* Новым является всё, и вспышка целого экрана — это не сигнал, а мигание.
       Снимок при этом обязан записаться, иначе не будет видно СЛЕДУЮЩИЙ. */
    expect(freshOf(null, ['1', '2', '3'])).toEqual([])
  })

  it('свежий — тот, кого в прошлом снимке не было', () => {
    expect(freshOf(['1', '2'], ['1', '2', '7'])).toEqual(['7'])
    expect(freshOf(['1', '2'], ['1', '2'])).toEqual([])
    /* ушедший никого не подсвечивает: подсветка про ПРИЕЗД */
    expect(freshOf(['1', '2'], ['1'])).toEqual([])
  })

  it('⚠️ вернувшаяся из отмены запись считается приехавшей, и это намеренно', () => {
    /* Отменённые в конверт не попадают вовсе (канва отбрасывает их до сборки
       блоков), поэтому возврат выглядит как приезд — им он и является для
       того, кто смотрит на экран. */
    expect(freshOf(['1'], ['1', '5'])).toEqual(['5'])
  })

  it('⛔ ключ памяти — ТОТ ЖЕ, что у легаси', () => {
    /* Разойдись они — человек, сходивший на `?ui=legacy` и обратно, получил бы
       вспышку всего дня разом. */
    expect(seenKey('2026-09-20')).toBe('dp_seen_2026-09-20')
  })

  it('хранилище: записали — прочли; чужой мусор читается как «не смотрели»', () => {
    writeSeen('2026-09-20', ['4', '9'])
    expect(readSeen('2026-09-20')).toEqual(['4', '9'])
    expect(readSeen('2026-09-21')).toBeNull()
    sessionStorage.setItem(seenKey('2026-09-22'), 'не json')
    expect(readSeen('2026-09-22')).toBeNull()
    sessionStorage.setItem(seenKey('2026-09-23'), '{"a":1}')
    expect(readSeen('2026-09-23')).toBeNull()
  })

  it('⚠️ номера приводятся к строкам: конверт несёт числа, хранилище — текст', () => {
    writeSeen('2026-09-20', ['7'])
    expect(freshOf(readSeen('2026-09-20'), ['7', '8'])).toEqual(['8'])
  })
})
