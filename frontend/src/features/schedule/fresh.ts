/**
 * Подсветка ПРИЕХАВШЕЙ записи (C26.5.4).
 *
 * ⭐ То самое событие, ради которого журнал висит открытым на стойке: бронь не
 * имеет права просто появиться между двумя кадрами незамеченной. Переход,
 * завершённый без подсветки, — потеря поведения рабочего процесса, а не
 * визуальная разница (слово Олега 19.09, рубеж выката).
 *
 * ⛔ «Свежее» — это НЕ «недавно создано»: ни отметки времени, ни поля от
 * сервера здесь нет и не заводится. Свежее = «этого номера не было на экране,
 * когда я смотрел в прошлый раз». Ровно так считает легаси, и отсюда два
 * следствия, оба намеренные: запись, вернувшаяся из отмены, подсветится, а
 * ПЕРЕЕХАВШАЯ на другой час — нет (номер тот же). Второе не дыра, а граница:
 * событие, ради которого всё делается, — приезд новой записи.
 * ⛔ Память — та же, что у легаси: `sessionStorage`, ключ на ДЕНЬ, набор
 * номеров. И ключ обязан совпадать буквально: человек, переключившийся на
 * `?ui=legacy` и обратно, иначе получил бы вспышку всего дня разом.
 * ⚠️ Именно `sessionStorage`, а не переменная: у легаси это единственное, что
 * переживает 303-повтор после действия. У React повтора нет, но память общая,
 * и вести её двумя способами значило бы развести два экрана.
 *
 * ⚠️ Первый показ дня не подсвечивает НИЧЕГО: новым является всё, и вспышка
 * всего экрана — это не сигнал, а мигание. Снимок при этом пишется, чтобы
 * следующий приезд был виден.
 */

/** Сколько держать пометку. Анимация 1.6 с (`.gappt.fresh` в panel.css) плюс
 *  запас: снять раньше — оборвать её на середине.
 *  ⛔ Снимать ПО ТАЙМЕРУ, а не по `animationend`: под
 *  `prefers-reduced-motion` анимации нет вовсе, события не будет, и пометка
 *  осталась бы на узле навсегда. У легаси её не снимали никогда — там узел
 *  умирал при первой же подмене, а у React он живёт. */
export const FRESH_MS = 1800

/** Ключ памяти дня. ⛔ Тот же, что печатает `panel.js`. */
export function seenKey(day: string): string {
  return `dp_seen_${day}`
}

/** Что было на экране в прошлый раз. `null` — не смотрели вовсе. */
export function readSeen(day: string): string[] | null {
  try {
    const raw = sessionStorage.getItem(seenKey(day))
    const got: unknown = raw === null ? null : JSON.parse(raw)
    return Array.isArray(got) ? got.map(String) : null
  } catch {
    /* приватный режим, запрещённое хранилище, чужой мусор в ключе */
    return null
  }
}

export function writeSeen(day: string, ids: string[]): void {
  try {
    sessionStorage.setItem(seenKey(day), JSON.stringify(ids))
  } catch {
    /* приватный режим: подсветки не будет, но экран работает */
  }
}

/**
 * Что приехало: номера, которых в прошлом снимке не было.
 *
 * ⚠️ `seen === null` — первый показ дня: возвращается ПУСТО, а не всё.
 */
export function freshOf(seen: readonly string[] | null, now: readonly string[]): string[] {
  if (seen === null) return []
  const was = new Set(seen)
  return now.filter((id) => !was.has(id))
}
