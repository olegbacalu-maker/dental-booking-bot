/**
 * Даты в браузере. ⚠️ Здесь ТОЛЬКО арифметика и числовой формат: румынские
 * слова (сокращение дня недели, название месяца) приходят с сервера — второй
 * их список здесь разошёлся бы с первым молча.
 */

/**
 * ISO-дата, сдвинутая на `days`. ⚠️ Полдень, а не полночь: `new Date('…T00:00')`
 * в поясе восточнее UTC уезжает на сутки назад при `toISOString()`, и «завтра»
 * оказывается сегодня. У клиники пояс Кишинёва, то есть ровно этот случай.
 */
export function shift(iso: string, days: number): string {
  const d = iso ? new Date(`${iso}T12:00:00`) : new Date()
  d.setDate(d.getDate() + days)
  return d.toISOString().slice(0, 10)
}

/** `2026-09-24` → `24.09`: короткая подпись соседнего дня на кнопке. */
export function dm(iso: string): string {
  const [, m, d] = iso.split('-')
  return `${d}.${m}`
}
