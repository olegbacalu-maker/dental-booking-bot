/**
 * Шов каталога — ЕДИНСТВЕННОЕ место, где подпись экрана становится текстом.
 *
 * Развилка закрыта до кода: [docs/dentpilot-2/i18n.md](../../../docs/dentpilot-2/i18n.md) §3.
 * Подписи по-прежнему принадлежат ЭКРАНУ (frontend.md › «Кто владеет
 * словами»): здесь не заводится ни одной строки и ни одной локали. Меняется
 * ровно одно — словарь экрана объявляется через `t()`, и когда каталог
 * появится, перевод включится без правки самих экранов:
 *
 *     const T = t('crypt', { title: 'Criptarea evidenței', … } as const)
 *     …
 *     <h2>{T.title}</h2>          // обращение НЕ меняется ни одно
 *
 * ⭐ Ключ резолвится в момент ОБРАЩЕНИЯ, а не на импорте. Модули грузятся в
 * произвольном порядке, а каталог приезжает инлайн-скриптом страницы: резолв
 * на импорте означал бы, что часть экранов успела прочитать пустоту, и это
 * зависело бы от порядка сборки — то есть менялось бы молча от правки, не
 * имеющей к тексту никакого отношения.
 *
 * ⭐ Румынский — золотая локаль, и она живёт В ФАЙЛАХ ЭКРАНОВ. Пока каталога
 * нет (сегодня) или нужного ключа в нём нет, отдаётся сам объект: диффа
 * поведения ноль. Отсюда и форма отката — пустой каталог, а не «язык ro».
 *
 * ⛔ Ключом НЕ является румынская строка (§2): пропущенный ключ при
 * строке-ключе выглядит идеально по-румынски, и сторож полноты не покраснеет
 * никогда — та же «полярность списков-исключений», что в карте проекта.
 */

/** Плоский каталог: `нс.ключ` → перевод. Пусто у золотой локали. */
export type Catalog = Record<string, string>

declare global {
  interface Window {
    /**
     * Каталог, который сервер кладёт в страницу инлайн-скриптом (§4).
     * ⚠️ Объявлен там `var`, а не `const`: живой журнал переисполняет
     * помеченные скрипты после подмены, и повторный `const` — SyntaxError.
     */
    DP_I18N?: Catalog
  }
}

/**
 * Словарь экрана, накрытый каталогом. Тип — ТОТ ЖЕ, что у переданного объекта,
 * поэтому `T.save` проверяется компилятором как и раньше, а опечатка в имени
 * ключа остаётся ошибкой сборки.
 *
 * ⚠️ Пустая строка в каталоге считается отсутствием перевода: пустая подпись
 * на экране — это кнопка без слова, и молчать о ней хуже, чем показать
 * румынскую. Полноту каталога сторожит сервер (§15, правило 2).
 */
export function t<T extends Record<string, string>>(ns: string, strings: T): T {
  return new Proxy(strings, {
    get(target, key, receiver) {
      if (typeof key !== 'string') return Reflect.get(target, key, receiver)
      const value = window.DP_I18N?.[`${ns}.${key}`]
      return typeof value === 'string' && value !== ''
        ? value
        : Reflect.get(target, key, receiver)
    },
  })
}
