# -*- coding: utf-8 -*-
"""Клиент Google — в сборку: JSON консоли вне репозитория → bot/app/core/gclient_build.py.

    python scripts\\embed_gclient.py [путь-к-json]

Путь — аргумент, иначе DENTART_GOOGLE_CLIENT, иначе D:\\DentProject\\secrets\\google-client.json.
Модуль пишется при каждой сборке: оставшийся от прошлой не уедет в новую. Нет файла или он не
Desktop-клиент — `CLIENT = None`, сборка идёт дальше: связь с Google в такой программе «не настроена».
Итог — одна строка без значений (её ищет пре-полёт выпуска в журнале сборки). Сгенерированный модуль —
в .gitignore: репозиторий публичный.
"""
import os
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "bot" / "app" / "core" / "gclient_build.py"
DEFAULT = pathlib.Path(r"D:\DentProject\secrets\google-client.json")
CONFIGURED = "google client: configured"
MISSING = "google client: NOT configured"

sys.path.insert(0, str(ROOT / "bot"))
from app.core import gauth  # noqa: E402


def render(client: gauth.Client | None) -> str:
    head = "# Generated by scripts/embed_gclient.py at build time. Not tracked by git.\n"
    if client is None:
        return head + "CLIENT = None\n"
    return head + f"CLIENT = {{'id': {client.id!r}, 'secret': {client.secret!r}}}\n"


def embed(src: pathlib.Path, out: pathlib.Path | None = None) -> bool:
    out = out or OUT
    try:
        client = gauth.client_of(src.read_bytes())
    except OSError:
        client = None
    out.write_bytes(render(client).encode("utf-8"))
    return client is not None


def main(argv: list[str]) -> int:
    src = pathlib.Path(argv[0] if argv else os.environ.get("DENTART_GOOGLE_CLIENT") or DEFAULT)
    print(CONFIGURED if embed(src) else MISSING)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
