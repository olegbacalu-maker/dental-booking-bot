def neck_of(tab):
    """Шейка коронки — первая строка таблицы: центр, радиусы на N_TRUNK углах
    (каждый второй из 96) и полуширины по x и z."""
    r0 = np.asarray(tab["r"][0], float)
    step = len(r0) // N_TRUNK
    assert step * N_TRUNK == len(r0), "углы шейки не делятся на углы ствола"
    th = 2 * np.pi * np.arange(N_TRUNK) / N_TRUNK
    rn = r0[::step]
    th96 = 2 * np.pi * np.arange(len(r0)) / len(r0)
    xs, zs = r0 * np.cos(th96), r0 * np.sin(th96)
    return float(tab["cx"][0]), float(tab["cz"][0]), th, rn, (xs.max() - xs.min()) / 2, (zs.max() - zs.min()) / 2


def single(name, tab):
    p = SINGLE[name]
    cx0, cz0, th, rn, an, bn = neck_of(tab)
    K = 24
    u = np.arange(K) / (K - 1)
    t = 1.0 - (1.0 - u) ** 1.35                      # строки гуще к апексу: там скругление
    d = p["L"] * t
    a0, b0 = 0.92 * an, 0.94 * bn
    rows, ox, oz = [], [], []
    for tk in t:
        k = taper(tk)
        blend = smoothstep(0.0, 0.3, tk)
        rs = section(th, a0 * k, b0 * k, n=p["n"], ling=p["ling"], conc=tuple(c * blend for c in p["conc"]))
        rd = (1.0 - blend) * rn * (1.0 - 0.1 * tk) + blend * rs
        rows.append(np.clip(rd / rn, 0.0, 1.5))
        ox.append(p["curve"][0] * tk ** 2.5)
        oz.append(p["curve"][1] * tk ** 2.0)
    rows[0] = np.ones(N_TRUNK)
    rows[-1] = np.zeros(N_TRUNK)
    return {"len": p["L"], "fur": p["L"], "theta": N_TRUNK,
            "trunk": {"d": d.tolist(), "ox": ox, "oz": oz, "w": [r.tolist() for r in rows]},
            "rt": N_ROOT, "list": []}


def multi(name, tab):
    p = MULTI[name]
    cx0, cz0, th, rn, an, bn = neck_of(tab)
    fur = p["fur"]
    # ствол: шейка сужается к фуркации, у входов фуркации — бороздки
    K = 9
    d = fur * np.linspace(0.0, 1.0, K)
    rows = []
    for dk in d:
        s = smoothstep(0.0, fur, dk)
        w = 1.0 - 0.18 * s
        for deg, depth in p["entries"]:
            w = w - depth * smoothstep(0.25 * fur, fur, dk) * np.exp(-(_adist(th, np.radians(deg)) / 0.35) ** 2)
        if p.get("mesial"):
            w = w - p["mesial"] * smoothstep(0.0, 0.3 * fur, dk) * np.exp(-(_adist(th, np.pi) / 0.45) ** 2)
        rows.append(np.asarray(w, float))
    rows[0] = np.ones(N_TRUNK)
    # дно ствола — свод, а не плита: ещё две строки ниже фуркации сходятся внутрь
    # (их закрывают корни; плоское дно давало уступ у фуркации)
    for dd, k in ((0.35, 0.8), (0.7, 0.5)):
        d = np.append(d, fur + dd)
        rows.append(rows[-1] * k if dd == 0.35 else rows[-2] * k)
    K = len(d)
    trunk = {"d": d.tolist(), "ox": [0.0] * K, "oz": [0.0] * K, "w": [r.tolist() for r in rows]}
    # корни: верх внутри ствола (на 1,6 мм выше фуркации), до своего апекса
    th_r = 2 * np.pi * np.arange(N_ROOT) / N_ROOT
    out = []
    R = 18
    u = np.arange(R) / (R - 1)
    t = 1.0 - (1.0 - u) ** 1.3
    for q in p["roots"]:
        top = fur - 1.6                                  # верх корня глубоко внутри ствола: стык не виден
        L = p["L"] * q["len"]
        dk = top + (L - top) * t
        x0, z0 = cx0 + q["x"] * an, cz0 + q["z"] * bn
        ax, az = q["ax"] * an, q["az"] * bn
        cx, cz, rr = [], [], []
        for tk in t:
            # у фуркации корень шире (переход ствола в корень), дальше — профиль моляра
            k = taper(tk, end=0.25, p=2.6) * (1.0 + 0.18 * (1.0 - smoothstep(0.0, 0.25, tk)))
            cx.append(x0 + ax * tk ** 1.5 + q["curve"] * tk ** 2.5)
            cz.append(z0 + az * tk ** 1.5)
            rr.append(section(th_r, q["a"] * an * k, q["b"] * bn * k, n=q["n"], conc=q["conc"]))
        rr[-1] = np.zeros(N_ROOT)
        out.append({"d": dk.tolist(), "cx": cx, "cz": cz, "r": [r.tolist() for r in rr]})
    return {"len": p["L"], "fur": fur, "theta": N_TRUNK, "trunk": trunk, "rt": N_ROOT, "list": out}


COUNT = {**{k: 1 for k in SINGLE}, **{k: len(v["roots"]) for k, v in MULTI.items()}}


def root_set(name, tab):
    """Корни типа `name` по таблице его коронки."""
    return single(name, tab) if name in SINGLE else multi(name, tab)


def check(name, rs):
    """Строки по возрастанию глубины, первая строка ствола — ровно шейка, радиусы
    конечны и неотрицательны, апекс — точка, выбросов по углу нет."""
    tr = rs["trunk"]
    d = np.asarray(tr["d"])
    assert (np.diff(d) > 0).all(), f"{name}: глубины ствола"
    w = np.asarray(tr["w"])
    assert np.allclose(w[0], 1.0), f"{name}: ствол не начинается шейкой"
    assert np.isfinite(w).all() and (w >= 0).all(), f"{name}: множители ствола"
    spike = float(np.abs(w - (np.roll(w, 1, 1) + np.roll(w, -1, 1)) / 2).max())
    for q in rs["list"]:
        r = np.asarray(q["r"])
        assert (np.diff(q["d"]) > 0).all(), f"{name}: глубины корня"
        assert np.isfinite(r).all() and (r >= 0).all(), f"{name}: радиусы корня"
        assert np.allclose(r[-1], 0.0), f"{name}: апекс не точка"
        spike = max(spike, float(np.abs(r - (np.roll(r, 1, 1) + np.roll(r, -1, 1)) / 2).max()))
    return spike
