def _r(x, z, a, b, ln, ax, az, curve, conc=(0.0, 0.0), n=2.0):
    """Корень многокорневого: верх (x, z), полуоси (a, b) — доли полуширин шейки;
    длина — доля `L`; апекс сдвинут на (ax, az) долей; изгиб апекса дистально, мм."""
    return dict(x=x, z=z, a=a, b=b, len=ln, ax=ax, az=az, curve=curve, conc=conc, n=n)


