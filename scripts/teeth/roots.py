"""Корни своих моделей зубов (25.10, волна 3; слово Олега: «корни вместо
конусов — 2–3 дня»). До них корни строила формула программы
(`toothGeometry.buildRoots`): сужение шейки + эллиптические конусы, без ствола
и фуркации.

Корень — «обобщённый цилиндр»: изогнутая ось (апекс уходит дистально, корни
многокорневых расходятся) и сечение на каждой глубине — суперэллипс с
вогнутостями на контактных сторонах (лента нижних резцов, «почка» второго
верхнего премоляра, широкий мезиальный корень нижнего моляра). Сечение у
шейки — САМА шейка коронки (первая строка таблицы `gen_teeth.table`):
корень продолжает её, и десна при рецессии садится на ту же стенку.

Выход — таблица `roots` рядом с таблицей коронки:
- `trunk` — ствол от шейки: глубины `d`, сдвиг центра `ox`/`oz` от центра
  шейки и `w[строка][угол]` — множитель радиуса ШЕЙКИ на этом угле (первая
  строка — ровно 1: шов коронки и корня невозможен по построению). У
  однокорневого ствол идёт до апекса (`w` → 0), у многокорневого — до
  фуркации `fur`, снизу его закрывает программа;
- `list` — корни многокорневого: глубины `d`, центр `cx`/`cz` и радиусы
  `r[строка][угол]`, в мм эталона коронки; начинаются внутри ствола, последняя
  строка — апекс (радиусы 0);
- `len` — глубина апекса самого длинного корня под шейкой, мм эталона: по ней
  программа приводит корни к длине сервера (`g.root`).

Оси — как у коронки: +x дистально, −x мезиально, +z щёчно/губно, −z язычно,
глубина d > 0 — вниз от шейки. Числа — мм эталона (Wheeler): длины корней,
положение и размер корней многокорневых — доли полуширин шейки.
"""
import numpy as np

N_TRUNK = 48          # углов ствола: каждый второй угол шейки (у коронки 96)
N_ROOT = 36           # углов корня


def smoothstep(e0, e1, x):
    t = np.clip((np.asarray(x, float) - e0) / (e1 - e0), 0.0, 1.0)
    return t * t * (3 - 2 * t)


def _adist(th, c):
    """Угловое расстояние до c, (−π, π]."""
    return (np.asarray(th) - c + np.pi) % (2 * np.pi) - np.pi


def taper(t, end=0.35, p=1.8):
    """Профиль корня по доле длины: полный у шейки, к апексу сужается и
    скругляется (касательная у апекса вертикальна — апекс круглый, не игла).
    Больше `p` — корень дольше держит ширину и сужается в апикальной трети
    (корни моляров), меньше — ровный конус (резцы)."""
    t = np.clip(np.asarray(t, float), 0.0, 1.0)
    return np.sqrt(np.clip(1.0 - t ** p, 0.0, 1.0)) * (1.0 - end * t)


def section(th, a, b, *, n=2.0, ling=1.0, conc=(0.0, 0.0), conc_w=0.38):
    """Радиус сечения корня под углом th: суперэллипс с полуосями a (MD) и b (BL,
    у язычной стороны ×ling), вогнутости `conc` = (D, M) — доля радиуса."""
    th = np.asarray(th, float)
    a, b = max(a, 1e-9), max(b, 1e-9)                 # у апекса полуоси 0 — радиус 0, без деления на ноль
    c, s = np.cos(th), np.sin(th)
    bb = np.where(s >= 0, b, b * ling)
    r = (np.abs(c / a) ** n + np.abs(s / bb) ** n) ** (-1.0 / n)
    k = 1.0 - conc[0] * np.exp(-(_adist(th, 0.0) / conc_w) ** 2) - conc[1] * np.exp(-(_adist(th, np.pi) / conc_w) ** 2)
    return r * k


