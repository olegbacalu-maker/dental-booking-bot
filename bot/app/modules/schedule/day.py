"""День экрана «Programări»: правила, из которых собирается его модель.

Здесь нет ни одной строки разметки: шапка дня, форма записи, «Lista zilei»,
карточки и кнопки исхода — функциями, их отдаёт JSON API (`/api/schedule/day`).
Сетку дня с 06.10 рисует канва (`canvas.py`, та же, что у панели); таблица
старой страницы с её ячейками снята 13.10 вместе со страницей. Её правила —
ряды непрерывным диапазоном, обед рядом, ключ записи `doctor_id` или снимок
имени, «занято» и «не принимает» порознь — живут в канве.
"""
from __future__ import annotations

from datetime import date, datetime

from ... import db
from ... import engine as eng
from ...core import sms_loop
from ...core.auth import PERM_SMS, can, request_user
from ...core.layout import _DOW_FULL, _DOW_ORDER, STATUS_LABEL, tg_configured
from ...core.visits import _age, all_status_actions, call_fields, list_rows


def day_title(d: date) -> str:
    """Подпись дня в шапке: «Jo 24.09.2026».

    ⚠️ Дата ОДИН раз. До 08-11 шапка печатала `{lbl} {d.isoformat()}`, то есть
    «Ma 11.08 2026-08-11» — один и тот же день двумя записями подряд и без
    разделителя. Год берётся из `d.year`, а не из ISO: day_label даёт только
    день с месяцем, и без года шапка не сказала бы, какой это август.
    ⛔ Сборка ОДНА на живой канал панели (`_panel_live` › `day_label`) и
    модель дня (`model` › `day_label`, экран «Programări»): сокращения дней
    недели румынские, и вторая сборка разошлась бы с первой молча — у панели и
    у «Programări» один и тот же день назывался бы по-разному. Живёт здесь, а не
    в routes: модель дня routes не импортирует.
    """
    return f"{eng.day_label(eng.Session(lang='ro'), d)}.{d.year}"


# Месяцы словами — ОДИН список на мини-календарь панели и дату словами:
# второго списка румынских названий в программе не заводится.
RO_MONTHS = ["Ianuarie", "Februarie", "Martie", "Aprilie", "Mai", "Iunie", "Iulie",
             "August", "Septembrie", "Octombrie", "Noiembrie", "Decembrie"]


def day_long(d: date, months=None) -> str:
    """Дата словами под заголовком панели и дня (08.10, макет): «Joi, 8
    octombrie 2026». Дни недели — тот же словарь, что у графика работы в
    настройках (`layout._DOW_FULL`), месяцы — `RO_MONTHS`."""
    m = months or RO_MONTHS
    return (f"{_DOW_FULL[_DOW_ORDER[d.weekday()]]}, {d.day} "
            f"{m[d.month - 1].lower()} {d.year}")


def column_spec(dk: str) -> str:
    """Подпись колонки под именем врача; выключенный помечается прямо здесь."""
    spec = eng.DOCTOR_SPEC.get(dk, "")
    if not eng.DOCTOR_META.get(dk, {}).get("active", True):
        spec = (spec + " · inactiv").strip(" ·")
    return spec


# Отбор «Lista zilei» по адресу `/admin/all?f=…` (до 01.10 туда вели плитки
# «Azi» панели). Фильтруется СПИСОК, не канва: «сколько пришло из бота» —
# вопрос к списку, а канва в этот момент отвечает на другой («что стоит в
# дне»), и прореживать её значило бы соврать про занятость.
# ⚠️ Отменённые в первых трёх фильтрах не считаются: «записей из бота» —
# это живые записи, а не след отменённых.
TILE_FILTERS = {
    "bot": ("prin bot",
            lambda r: r["source"] == "bot" and r["status"] != "cancelled"),
    "rec": ("recepție",
            lambda r: r["source"] == "manual" and r["status"] != "cancelled"),
    "urg": ("urgențe",
            lambda r: r["service"] in eng.URGENT_LABELS
            and r["source"] != "note" and r["status"] != "cancelled"),
    "noshow": ("neprezentări", lambda r: r["status"] == "noshow"),
}


def note_ends(d: date) -> list[int]:
    """Часы, которыми МОЖЕТ КОНЧИТЬСЯ блокировка слота: открытый час плюс один.

    ⚠️ Обеденный час выпадает из `day_slots`, а значит и отсюда: при обеде
    13–14 закончить блокировку в 14:00 нельзя, ближайшие концы — 13:00 и
    15:00. Это не оплошность: заметка блокирует ЧАСЫ ПРИЁМА, а обеденного
    часа среди них нет.
    """
    return [x.hour + 1 for x in eng.day_slots(d)]


def form_spec(d: date, items: list, sel_doctor: str = "",
              sel_time: str = "") -> dict:
    """Что предлагает форма записи: врачи, ИХ часы, услуги и предвыбор.

    ⚠️ Часы здесь СВОИ, а не из канвы. Канва рисует непрерывный диапазон, и
    обеденный час в ней есть (заштрихованным); форма предлагает только те
    получасовые старты, куда влезает приём.
    ⚠️ Влезает — это всегда 30 минут, а не длительность выбранной услуги:
    список ОДИН на все услуги. Пересчёт «по-умному» отнял бы 17:30 у
    получасового приёма в клинике, закрывающейся в 18:00, — час, который
    сегодня законен; а часовой визит на 17:30 всё равно отобьёт `outside`.
    ⛔ Пустое окно врача подменяется часами клиники (`or hours`): пустой выбор
    часа не отправил бы время вовсе, и вместо честного отказа «Medicul nu
    lucrează la ora aleasă» вышел бы отказ разбора.
    ⚠️ `items` — НЕ колонки канвы: сюда идут активные врачи справочника,
    потому что выключенному запись ответит `bad_off`, а колонка у него на
    канве остаётся, пока есть записи дня.
    """
    def _starts(fits) -> list[str]:
        out = []
        for x in eng.day_slots(d):
            for m in (0, 30):
                st = x.replace(minute=m)
                if fits(st):
                    out.append(st.strftime("%H:%M"))
        return out

    hours = _starts(lambda st: eng.fits_clinic(st, 30))
    times = {dk: _starts(lambda st, k=dk: eng.fits_doctor(k, st, 30)) or hours
             for dk, _n in items}
    cur = sel_doctor if sel_doctor in times else (items[0][0] if items else "")
    return {
        "doctors": [{"id": dk, "name": name} for dk, name in items],
        "times": times,
        # часы клиники: ими подменяется пустое окно врача, ими же живёт форма,
        # когда активных врачей нет вовсе
        "hours": hours,
        "services": [{"id": k, "label": v["ro"]} for k, v in eng.SERVICES.items()],
        "doctor": cur,
        "time": sel_time if sel_time in times.get(cur, hours) else "",
        "birth_max": birth_max(),
        "sms": sms_box(),
    }


def birth_max() -> str:
    """Потолок поля «дата рождения» — СЕГОДНЯ В ЧАСАХ КЛИНИКИ.

    ⛔ Не `date.today()`. Поле уехало в живой конверт (`slotform`), а значит в
    отпечаток: считанное по часам машины, оно переворачивало бы отпечаток в
    полночь по чужому поясу и расходилось бы в прогоне под `TZ=UTC0` с
    остальной моделью, которая вся живёт в `eng.TZ`.
    ⚠️ Одна функция на форму модели дня и конверт панели: два «сегодня» в
    двух местах разошлись бы ровно в полночь и ровно на сутки.
    """
    return datetime.now(eng.TZ).date().isoformat()


def sms_box() -> bool:
    """Показывать ли в окне записи галочку «SMS reminder» (Олег 19.10).

    Два условия, оба нужны: пакет РАБОТАЕТ (`sms_loop.active()` — то же
    состояние, что решает лист acord и отправку: без него галочка обещала бы
    напоминание, которого не будет) и у вошедшего есть право `PERM_SMS` (врач
    SMS не видит вовсе, Олег 22.10). ⚠️ Ответ зависит от вошедшего — как и
    касса «La recepție» (`desk.collect` по `PERM_MONEY`) в том же живом
    конверте: конверт строится на каждый запрос, отпечаток — от отправленного,
    и у одного человека он детерминирован, как и было.
    """
    return sms_loop.active() and can(request_user(), PERM_SMS)


def slot_form(d: date) -> dict:
    """Что нужно диалогу пустого часа на ПАНЕЛИ — и только это.

    ⛔ Имя `slotform`, а не `form`: у модели дня `form` несёт ещё врачей, их
    часы и предвыбор, и ключ с тем же именем, но меньшим составом — ловушка
    для следующего, кто скопирует форму записи. Панели врачи и часы не нужны:
    врач приходит из колонки, час — из ячейки, получас — переключателем.
    """
    del d  # день приходит параметром ради симметрии с `form_spec`
    return {"services": [{"id": k, "label": v["ro"]} for k, v in eng.SERVICES.items()],
            "birth_max": birth_max(), "sms": sms_box()}

