def appt_view(r, dk: str, cards: dict | None, colors) -> dict:
    """Одна запись глазами канвы (`canvas.blocks` поверх этого добавляет
    геометрию): то же, что показывает карточка.

    `colors` и `cards` передаются аргументами по той же причине, что и у
    недели: они живут в `routes`/`core.visits`, а импорт оттуда замкнул бы
    круг. ⛔ Перетаскивание описывается ОДНИМИ полями на оба экрана дня:
    минуты от полуночи, длительность и признаки «занимает интервал» и «можно
    тащить». Разойдись они — перенос на одном из экранов молча перестал бы
    работать, а поймать это можно только руками.
    """
    st = r["starts_at"].astimezone(eng.TZ)
    dur = int(r.get("duration_min") or 60)
    live = r["status"] in db.ACTIVE_STATUSES
    if r["source"] == "note":
        # ⛔ `status` у заметки — не для показа, а чтобы по нему СПРОСИТЬ кнопку
        # в `note_actions` (C26.5.3-d). Без него клиенту пришлось бы считать
        # заметку «confirmed» по умолчанию — то есть завести в браузере ВТОРОЕ
        # знание о состоянии, а эта пара расходилась молча уже дважды (08-12,
        # 08-16). ⚠️ Матрица заметки знает два состояния из шести, и это не
        # оплошность: у неё нет прихода и исхода, есть «убрать» и «вернуть».
        # Заметка, уведённая в чужой статус, честно останется без кнопок.
        return {"kind": "note", "id": r["id"], "time": st.strftime("%H:%M"),
                "text": r["service"], "status": r["status"],
                "min": st.hour * 60 + st.minute,
                "dur": dur, "busy": live, "movable": bool(dk) and live}
    bg, bar = colors(r)
    return {
        "kind": "appt", "id": r["id"], "time": st.strftime("%H:%M"),
        "name": r["name"] or "—", "service": r["service"],
        "phone": r["phone"] or "", "status": r["status"],
        "urgent": r["service"] in eng.URGENT_LABELS,
        "source": r["source"], "dur": dur,
        # ⛔ ДВА имени, и это не дублирование. Полное значение носит имя БЕЗ
        # суффикса — из него правят; обрезок носит имя, по которому его нельзя
        # взять по ошибке (у обоих тип `str`, и типы не возразят). Обрезает
        # по-прежнему СЕРВЕР: длина — данные, а не оформление, обрежь её в
        # браузере — и пересохранение через диалог укоротит текст в базе
        # (08-16). ⭐ Этим же ПОСТРОЕНИЕМ закрыта дыра живого канала: полное
        # значение лежит в отпечатке, поэтому правка 61-го знака приезжает
        # вторым рабочим местом, а не тонет в проекции (опыт 19.09,
        # live-contract › 6c).
        "comment": r["comment"] or "",
        "comment_cut": (r["comment"] or "")[:60],
        # ⛔ Слово статуса и возраст приезжают ГОТОВЫМИ: второй словарь статусов
        # в браузере — это «Finalizat» в одном месте и «a venit» в другом
        # (ломалось дважды, 08-12 и 08-16), а свой счёт возраста разойдётся с
        # серверным в день, когда появится месяц рождения.
        "status_label": STATUS_LABEL.get(r["status"], r["status"]),
        "age": _age(r.get("birth_year")),
        # ⛔ Три поля ниже — ровно то, чего диалогу карточки не хватало в
        # блоке, и НИ ОДНИМ больше (C26.5.3-a). Вторая структура «карточка»
        # на живой поверхности не заводится: она несёт ОТМЕНЁННЫЕ записи,
        # которых на канве негде нажать, а всё, что попало в конверт, попало
        # в отпечаток — правка у невидимой записи гнала бы перерисовку, в
        # которой на экране не меняется ничего (разбор — interaction-contract).
        # ⚠️ `doctor` — СНИМОК имени из самой записи, а не имя колонки: визит
        # показывается под тем врачом, под которым записан, и после
        # переименования шапка колонки и диалог говорят РАЗНОЕ. Так и надо.
        "doctor": r["doctor"] or "",
        "pid": r.get("patient_id"),
        "rec": bool(r.get("has_rec")),
        # отметка звонка и «можно ли её ставить» — тем же правилом, что у
        # карточки дня (`core.visits.call_fields`, 12.10)
        **call_fields(r),
        "clickable": bool(cards is not None and r["id"] in cards),
        "bg": bg, "bar": bar,
        # перетаскивание — одними полями на панель и «Programări». `busy` —
        # статусы, которые считает `db._conflicts` (по ним браузер
        # предупреждает о столкновении ДО отправки); ⛔ тащить можно только
        # активный визит из колонки НАСТОЯЩЕГО врача: у колонки-сироты
        # (легаси-имя без id) `dk` пуст — переносить оттуда некуда
        "min": st.hour * 60 + st.minute, "busy": live,
        "movable": bool(dk) and live,
    }


def model(d, items: list, cards: dict | None, form_items: list | None = None,
          rows: list | None = None, f: str = "") -> dict:
    """День экрана «Programări» данными: шапка, врачи, форма, «Lista zilei» —
    и всё, чем живут диалоги: концы блокировки, карточки, кнопки исхода. Канву
    кладёт вызывающий (`routes._day_model`) — тем же `canvas.model`, что у
    панели.

    ⚠️ `items` — врачи дня (выбор врача в шапке «Toți medicii»): активные плюс
    выключенный, пока у него есть записи этого дня.
    ⛔ `form_items` — врачи ФОРМЫ, и это НЕ `items`: записать в выключенного
    врача нельзя (`bad_off`). Возьми клиент врачей из `doctors` — регистратура
    выбрала бы выключенного и получила отказ на ровном месте, а у разработчика
    оба списка совпадают. `None` — формы нет вовсе (день выключенного врача).
    ⚠️ Карточки приезжают ЦЕЛИКОМ, включая отменённые, которых на канве нет:
    отменённую запись открывают из «Lista zilei», чтобы вернуть. И комментарий
    в них ПОЛНЫЙ, а в блоке канвы обрезан до 60 — диалог обязан править
    полный, иначе пересохранение без единой правки укоротит текст (прайор
    08-16).
    """
    return {
        "date": d.isoformat(), "day_label": day_title(d),
        # дата словами — подзаголовок экрана «Programări» (08.10, макет)
        "day_long": day_long(d),
        "doctors": [{"id": dk, "name": name, "spec": column_spec(dk)}
                    for dk, name in items],
        "form": form_spec(d, form_items) if form_items is not None else None,
        "note_ends": note_ends(d),
        # ключи строками: так они приезжают из JSON, и клиент ищет карточку
        # строкой (`cards[String(id)]`)
        "cards": {str(k): v for k, v in (cards or {}).items()},
        "actions": all_status_actions(),
        "note_actions": all_status_actions(is_note=True),
        # «Sursă» в «Lista zilei» — только у клиники с ботом (06.10): без него
        # там везде «manual», и колонка ничего не различает. Тот же признак
        # прячет и весь остальной интерфейс бота (`tg_configured`).
        "source_col": tg_configured(),
        **_list_part(rows or [], f),
    }


def _list_part(rows: list, f: str) -> dict:
    """«Lista zilei» и её отбор. Отбор режет ТОЛЬКО список: канва в этот
    момент отвечает на другой вопрос — что стоит в дне, — и прореживать её
    значило бы соврать про занятость."""
    flt = TILE_FILTERS.get(f)
    if not flt:
        return {"list": list_rows(rows), "filter": None}
    label, pred = flt
    hits = [r for r in rows if pred(r)]
    return {"list": list_rows(hits),
            "filter": {"key": f, "label": label, "count": len(hits)}}
