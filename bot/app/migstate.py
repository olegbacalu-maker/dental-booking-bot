"""`migration.json` — граница транзакции переезда. Один владелец на весь файл.

Контракт — `docs/dentpilot-2/migration-contract.md` › «граница транзакции, а не
лог» и `split-contract.md`. Здесь ровно чтение и запись; РЕШЕНИЯ принимает
`relocate`, а работу делают шаги 4–8, которых ещё нет.

⭐ **Почему отдельный модуль, а не внутри `relocate`.** `relocate` объявлен
пишущим НОЛЬ байт, и это свойство сторожится разбором исходника
(`test_relocate.suite_no_drivers` ищет там `os.replace(` и `shutil.copy(`).
Дописать запись туда значило бы снять сторожа с шагов 1–3 ради шага, который к
ним не относится. Чтение файла `relocate` зовёт отсюда — владелец остаётся один.

⚠️ Модуль предзагрузочного слоя: из проекта только `paths`. Файл читает
ЛАУНЧЕР, до того как приложение существует, — иначе «какую базу открыть»
зависело бы от открытой базы.

⭐ **Состояний столько, сколько РАЗНЫХ ОТВЕТОВ на вопрос «что делать сейчас».**
Лишнее состояние не описывает мир точнее — оно заводит ещё одно окно, в котором
можно умереть, и ещё одну ветку, которую никто не исполнял.

| Что на диске | Что это значит | Что делает следующий запуск |
|---|---|---|
| файла НЕТ | переезд не начинался | обычная работа; решает `relocate.survey()` |
| `chosen: "new"` | человек выбрал корень, в котором работает | обычная работа, вопрос закрыт |
| `chosen: "old"` | человек подтвердил ИСТОЧНИК; копия разрешена, но НЕ начата | обычная работа; Copy-only вправе начаться |
| `authoritative: "old"` | копия начата и НЕ зафиксирована | ⛔ работать в СТАРОМ корне, копию считать мусором |
| `authoritative: "new"` | переключение зафиксировано | работать в новом корне |

⚠️ `chosen: "old"` НЕ переключает рабочий корень, и это не полумера. Человек
сказал «настоящая картотека — старая», но переносит её Copy-only, а его ещё
нет; объявить старый корень рабочим прямо сейчас значило бы начать ПИСАТЬ в
источник, который до конца переезда обязан оставаться контрольным. Поэтому
клиника до появления шага 4 продолжает в назначении — и сообщение на экране
обязано сказать об этом словами, а не сделать вид, что переезд состоялся.

⛔ Запись только целиком и только через `os.replace`: файл в любой момент либо
старый целиком, либо новый целиком. Запись «на месте» (открыть, усечь, писать)
это свойство теряет, и теряет молча — ровно как теряла её запись `auth_fail`
до аудита 08-20.
"""
from __future__ import annotations

import json
import os
import pathlib

from . import paths

NAME = "migration.json"
SCHEMA = 1

# Ответы человека на экране раздвоения. ⛔ Третьего («объедини») не существует и
# появиться не может: слияние двух картотек — это сверка вручную, и делает её
# человек, зная, какая запись верна.
CHOICE_OLD = "old"
CHOICE_NEW = "new"


def path(anchor: pathlib.Path | str | None = None) -> pathlib.Path | None:
    """`<ANCHOR>\\migration.json`. ⚠️ ANCHOR — корень, который вычислил лаунчер
    (`$DENTART_DATA_DIR`), а не папка программы и не папка базы: файл переживает
    и переустановку программы, и смену места картотеки."""
    root = pathlib.Path(anchor) if anchor is not None else paths.data_root()
    return root / NAME if root is not None else None


def state(anchor: pathlib.Path | str | None = None) -> dict:
    """Что на диске, ОДНИМ словарём. Ключи есть всегда — ветвиться по наличию
    ключа значит однажды забыть ветку.

    `present` · `broken` · `chosen` · `authoritative` · `old` · `new` · `raw`.

    ⛔ Нечитаемый файл — это `broken`, а НЕ «файла нет». Различие принципиально
    и того же класса, что у `auth._auth_broken`: усечённый обрывом записи файл
    иначе неотличим от отсутствующего, и следующий запуск начал бы переезд
    заново поверх наполовину сделанного. Тот же ответ и у файла из будущей
    версии: чужую `schema` мы не понимаем и делать вид, что поняли, не вправе.
    """
    out = {"present": False, "broken": False, "chosen": "",
           "authoritative": "", "old": "", "new": "", "raw": {}}
    p = path(anchor)
    if p is None or not p.exists():
        return out
    out["present"] = True
    try:
        rec = json.loads(p.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        out["broken"] = True
        return out
    if not isinstance(rec, dict) or int(rec.get("schema") or 0) != SCHEMA:
        out["broken"] = True
        return out
    out["raw"] = rec
    for k in ("chosen", "authoritative", "old", "new"):
        v = rec.get(k)
        out[k] = v if isinstance(v, str) else ""
    return out


def settled(anchor: pathlib.Path | str | None = None) -> bool:
    """Отвечал ли человек на вопрос о раздвоении.

    ⚠️ Битый файл считается ОТВЕЧЕННЫМ намеренно. Экран, вернувшийся из-за
    повреждённого файла, предложил бы выбрать заново — а выбор, возможно, уже
    сделан и копия начата. Молчать тут честнее, чем спросить второй раз; сам
    `broken` виден в `state()` и попадает в лог.
    """
    st = state(anchor)
    return bool(st["chosen"] or st["authoritative"] or st["broken"])


def record_choice(anchor: pathlib.Path | str, *, old: str, new: str,
                  choice: str, at: str) -> pathlib.Path:
    """Записать ОТВЕТ человека. Зовётся ровно один раз — после подтверждения.

    ⛔ Ни одной причины звать это раньше подтверждения не существует. Файл,
    созданный в момент ОБНАРУЖЕНИЯ, нарушил бы свойство, на котором стоят шаги
    1–3 («ни одного записанного байта», проверяется снимком дерева), и занял бы
    состояние «переезд начат» под вопрос, на который ещё не ответили.

    ⚠️ `old` и `new` пишутся ОБА и всегда, даже когда выбран второй: запись
    обязана называть и отвергнутый корень. «Видно и обратимо» — вторая половина
    защиты, без которой PIN остаётся следом, а не замком.
    """
    if choice not in (CHOICE_OLD, CHOICE_NEW):
        raise ValueError(f"ответа {choice!r} на этом экране не существует")
    p = path(anchor)
    if p is None:
        raise RuntimeError("корень не назван — записывать выбор некуда")
    rec = {"schema": SCHEMA, "chosen": choice, "old": old, "new": new,
           "confirmed_at": at}
    # Атомарно, тем же приёмом, что auth.json и счётчик попыток: tmp в ТОЙ ЖЕ
    # папке (os.replace атомарен только в пределах тома), fsync до подмены.
    tmp = p.with_name(p.name + ".tmp")
    with open(tmp, "w", encoding="utf-8") as f:
        f.write(json.dumps(rec, indent=1, ensure_ascii=False))
        f.flush()
        os.fsync(f.fileno())
    os.replace(tmp, p)
    return p
