# --- морфология по FDI ---
_INCISOR_C = {11, 21, 31, 41}
_INCISOR_L = {12, 22, 32, 42}
_CANINE = {13, 23, 33, 43}
_PREMOLAR = {14, 15, 24, 25, 34, 35, 44, 45}

# Молочный прикус — квадранты 5-8 (55-51, 61-65, 85-81, 71-75), по 5 зубов.
# ⚠️ Позиции 4 и 5 у молочных — МОЛЯРЫ, а не премоляры: премоляров в молочном
# прикусе не существует, и «отобразить 54 на 14» дало бы неверную морфологию
# ровно там, где её видно (два бугра вместо трёх).
_MILK_QUADRANTS = (5, 6, 7, 8)


def is_milk(fdi: int) -> bool:
    return fdi // 10 in _MILK_QUADRANTS


def tooth_class(fdi: int) -> str:
    if is_milk(fdi):
        pos = fdi % 10
        if pos == 1:
            return "incisor_c"
        if pos == 2:
            return "incisor_l"
        if pos == 3:
            return "canine"
        return "molar"          # 4 и 5 — молочные моляры
    if fdi in _INCISOR_C:
        return "incisor_c"
    if fdi in _INCISOR_L:
        return "incisor_l"
    if fdi in _CANINE:
        return "canine"
    if fdi in _PREMOLAR:
        return "premolar"
    return "molar"


def is_upper(fdi: int) -> bool:
    """Верхняя дуга: постоянные 1-2 и молочные 5-6. Без молочных квадрантов
    верхний молочный ряд рисовался бы корнями вверх."""
    return fdi // 10 in (1, 2, 5, 6)


def root_count(fdi: int) -> int:
    """Корней: верхние моляры 3, нижние 2, верхний первый премоляр 2, прочие 1."""
    cls = tooth_class(fdi)
    if cls == "molar":
        return 3 if is_upper(fdi) else 2
    if fdi in (14, 24):
        return 2
    return 1


# ⭐ КАНОН: все контуры рисуются мезиальной стороной ВПРАВО. Зуб не симметричен
# — у клыка вершина смещена мезиально, у резца мезиальный угол острее
# дистального, корни моляра наклонены дистально. Пока контуры были зеркальны
# сами себе, эта асимметрия была не нужна и её не было; теперь она есть, и
# сторону выбирает ОДНА обёртка, а не каждая кривая.
# ⛔ Отсюда: в геометрии ниже НЕТ ветвлений по квадранту. Появится хоть одно —
# и половина челюсти начнёт отличаться от другой не зеркалом, а рисунком.
def mesial_right(fdi: int) -> bool:
    """Мезиальная сторона — ближе к средней линии. На экране квадранты 1/4
    (и молочные 5/8) лежат СЛЕВА, значит их середина справа."""
    return fdi // 10 in (1, 4, 5, 8)


def mirrored(fdi: int) -> bool:
    """Нужно ли отразить: у квадрантов 2/3/6/7 мезиальная сторона слева."""
    return not mesial_right(fdi)


def _sx(x: float, k: float) -> float:
    """Сжатие по ширине относительно центра — так один контур даёт и
    центральный резец, и боковой, и третий моляр."""
    return CX + (x - CX) * k


def _p(*pts: float) -> str:
    return " ".join(f"{v:.1f}" for v in pts)


