def crown_path(fdi: int) -> str:
    """Замкнутый контур коронки. Низ контура = шейка зуба."""
    cls = tooth_class(fdi)
    k = _width_k(fdi)
    s = lambda x: _sx(x, k)  # noqa: E731

    # ⭐ ГЛАВНОЕ СВОЙСТВО ФОРМЫ: коронка ШИРЕ у жевательного края и уже у шейки.
    # До 08-16 было наоборот (шейка 20 при крае 17), и зуб читался листом —
    # ошибка не всплывала нигде, потому что «неправильно» тут не падает и не
    # логируется, а видно только глазом на кадре. Ширину шейки ниже держит
    # проверка в tests	est_teeth.py: она сравнивает крайние точки контура.
    if cls in ("incisor_c", "incisor_l"):
        # Режущий край прямой, но углы РАЗНЫЕ: мезиальный (справа) почти
        # прямой, дистальный заметно скруглён. Это первое, по чему на снимке
        # отличают правый резец от левого, и видно даже на 38 px
        return (f"M {_p(s(15), 46)} C {_p(s(13.4), 33, s(12.4), 20, s(12.8), 13)} "
                f"Q {_p(s(13.4), 7.8, s(18.4), 7.3)} L {_p(s(28.8), 7.2)} "
                f"Q {_p(s(31.5), 7.4, s(31.6), 11.6)} "
                f"C {_p(s(31.8), 19, s(30.8), 33, s(29), 46)} Z")
    if cls == "canine":
        # ⭐ Вершина СМЕЩЕНА МЕЗИАЛЬНО: мезиальный скат короткий и крутой,
        # дистальный длинный и пологий. Клык, у которого вершина по центру,
        # выглядит не клыком, а заострённым резцом
        return (f"M {_p(s(14.5), 48)} C {_p(s(12.5), 34, s(11.5), 20, s(13.5), 12)} "
                f"Q {_p(s(16.5), 6.2, s(24.5), 4.4)} "
                f"Q {_p(s(29.4), 5.6, s(30.5), 13)} "
                f"C {_p(s(32.5), 21, s(31.5), 34, s(29.5), 48)} Z")
    if cls == "premolar":
        # щёчный бугор (мезиальнее и ВЫШЕ) и язычный, выглядывающий ниже
        return (f"M {_p(s(12.5), 46)} C {_p(s(10.5), 32, s(9.5), 19, s(12), 12)} "
                f"Q {_p(s(15.2), 7.4, s(18.4), 12.4)} "
                f"Q {_p(s(21.6), 16, s(24.6), 11.6)} "
                f"Q {_p(s(28.2), 5.8, s(32), 11)} "
                f"C {_p(s(34.5), 19, s(33.5), 32, s(31.5), 46)} Z")
    # Моляр: три бугра РАЗНОЙ высоты — мезиальный самый высокий, дистальный
    # самый низкий. Ровные бугры читаются короной, а не жевательной поверхностью
    return (f"M {_p(s(9), 44)} C {_p(s(6.5), 29, s(5.5), 16, s(9.2), 11.4)} "
            f"Q {_p(s(12.4), 7.6, s(15.6), 11.8)} Q {_p(s(18.6), 15.4, s(21.6), 14.8)} "
            f"Q {_p(s(24.8), 14.2, s(27.8), 10.2)} Q {_p(s(31), 5.8, s(34.5), 10.2)} "
            f"C {_p(s(38.5), 16, s(37.5), 29, s(35), 44)} Z")


# Ширина зуба — ПРОИЗВЕДЕНИЕ трёх множителей, а не одно число: класс, челюсть,
# позиция в ряду. Раньше был один, и резец выходил 0.58 ширины моляра при
# настоящих 0.81 — на дуге это читалось «спички между молярами». Числа взяты
# от мезио-дистальных размеров (моляр ≈10.5 мм принят за единицу): верхний
# центральный 8.5, боковой 6.5, клык 7.6; нижние заметно уже — 5.3/5.9/6.9.
# ⚠️ Контуры при этом НЕ трогаются: _sx сжимает и коронку, и корень одним
# коэффициентом, поэтому шейка корня остаётся внутри шейки коронки сама.
_K_CLASS = {"incisor_c": 1.38, "incisor_l": 1.09, "canine": 1.14,
            "premolar": 1.0, "molar": 1.0}
_K_LOWER = {"incisor_c": 0.68, "incisor_l": 0.93, "canine": 0.92,
            "premolar": 1.0, "molar": 1.0}
_K_MILK = {1: 0.86, 2: 0.80, 3: 0.85, 4: 0.86, 5: 0.92}


def _width_k(fdi: int) -> float:
    """Коэффициент ширины: боковой резец уже центрального, третий моляр —
    мельче первого, нижние резцы — заметно уже верхних."""
    cls = tooth_class(fdi)
    pos = fdi % 10
    k = _K_CLASS.get(cls, 1.0)
    if not is_upper(fdi):
        k *= _K_LOWER.get(cls, 1.0)
    if is_milk(fdi):
        # молочный всегда мельче своего постоянного преемника — множителем,
        # а не своим набором чисел: иначе нижний молочный резец оказывался
        # ШИРЕ постоянного, потому что про челюсть его таблица не знала
        return k * _K_MILK.get(pos, 0.8)
    if cls == "premolar":
        return k * (0.94 if pos == 4 else 0.90)
    if cls == "molar":
        return k * {6: 1.0, 7: 0.95, 8: 0.88}.get(pos, 1.0)
    return k


