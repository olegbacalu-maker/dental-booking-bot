# Отметка — то, что живёт ПОВЕРХ находки. Состояние отвечает на вопрос «что с
# зубом», отметка — «что с ним делают», и это РАЗНЫЕ вопросы: зуб бывает
# кариозным и одновременно в работе.
# ⚠️ Пока «în tratament» стояло восьмым значением STATE_RO, второй выбор молча
# вытеснял первый: врач ставил кариес, потом лечение — и кариес исчезал с фиши
# и с подписываемой 043/e (08-17, вопрос Олега). Колонка одна, значение одно,
# и «совместить» было нечем.
# ⭐ Набор, а не флаг: вторая отметка («под наблюдением», «направлен к
# специалисту») ложится сюда же и не требует ни колонки, ни миграции — в базе
# лежит СПИСОК. Полярность списка безопасная: незнакомое имя отбрасывается, а
# не принимается «всем, кроме».
TOOTH_MARKS = ("tratament",)
MARK_RO = {"tratament": "În tratament"}


def pack_marks(marks) -> str:
    """Набор отметок → строка в каноническом порядке TOOTH_MARKS.

    Строкой по той же причине, что и поверхности (`pack_surfaces`): их единицы,
    читает их всегда сам зуб целиком, и отдельная таблица потребовала бы своей
    миграции и своего каскада удаления пациента ради одной пары."""
    got = set(marks or ())
    return ",".join(m for m in TOOTH_MARKS if m in got)


def mark_list(packed) -> list:
    """Строка (или готовый список) → отметки в каноническом порядке.

    Принимает и то, и другое НАМЕРЕННО: из базы приходит строка, из формы —
    список, а порядок и белый список должны быть одни на оба пути."""
    got = set(packed.split(",") if isinstance(packed, str) else (packed or ()))
    return [m for m in TOOTH_MARKS if m in got]


def _mark_halo(path: str, marks) -> list:
    """Ореол по контуру — рисунок отметки.

    ⭐ Рисуется ПЕРВЫМ, под самим зубом: наружу выходит только ободок, а всё,
    что внутри силуэта, закрывает сам зуб. Отсюда главное свойство — отметка
    НИЧЕГО не закрывает: ни поле поражённой поверхности, ни крест удаления, ни
    винт импланта. Значок поверх зуба пришлось бы уводить от каждого из них по
    отдельности, и на каком-нибудь состоянии он всё равно сел бы на смысл.
    ⚠️ И по той же причине ободок годится ДЛЯ ЛЮБОГО состояния, включая
    «lipsă»: силуэт рисуется всегда, даже призраком.
    """
    out = []
    for m in mark_list(marks):
        out.append(f"<path d='{path}' fill='none' stroke='{MARK_COLORS[m]}' "
                   f"stroke-width='6' stroke-linejoin='round' opacity='.85'/>")
    return out

# ---------------------------------------------------------- поверхности

SURFACE_ORDER = "MODVL"

# Состояния, которые бывают У ПОВЕРХНОСТИ, а не у зуба целиком. Порядок =
# порядок ТЯЖЕСТИ: из смеси зуб называется первым найденным. Коронка, имплант,
# удаление и отсутствие сюда не входят — они про весь зуб, и «коронка на
# мезиальной» не значит ничего.
# ⚠️ Появится третье поверхностное состояние — дописать СЮДА, а не заводить
# «всё, кроме»: правило вида «не карие, значит пломба» живёт ровно до второго
# исключения и ломается молча (грабля из карты про PLAN_ACTIVE).
SURFACE_STATES = ("carie", "obturatie")


def pack_surfaces(sfmap: dict) -> str:
    """{поверхность: состояние} → «M:carie,O:obturatie» в каноническом порядке.

    Строкой, а не таблицей на пять строк: на зуб их максимум пять, читает их
    всегда сам зуб целиком, и отдельная таблица потребовала бы своей миграции,
    своих индексов и своего каскада удаления пациента ради пяти пар."""
    return ",".join(f"{k}:{sfmap[k]}" for k in SURFACE_ORDER
                    if sfmap.get(k) in SURFACE_STATES)


def surface_map(state: str, surfaces: str = "", packed: str = "") -> dict:
    """{поверхность: состояние} для зуба.

    ⚠️ ЕДИНСТВЕННОЕ место, где решается, что значит пустая колонка. У записей
    старше 08-16 её нет вовсе, и они означают ровно то, что означали: все
    отмеченные поверхности в состоянии ЗУБА. Разложить это миграцией по данным
    можно было бы, но незачем — правило умещается в одну строку и живёт здесь,
    а не копией у каждого читателя."""
    if packed:
        out = {}
        for part in packed.split(","):
            k, _, v = part.partition(":")
            if k in SURFACE_ORDER and v in SURFACE_STATES:
                out[k] = v
        if out:
            return out
    if state in SURFACE_STATES:
        return {k: state for k in SURFACE_ORDER if k in (surfaces or "")}
    return {}


def tooth_state_of(sfmap: dict, fallback: str) -> str:
    """Как зуб называется целиком, когда поверхности разные: по самой тяжёлой.

    Нужно потому, что состояние зуба читают печатная 043/e, выгрузка по 195-му,
    летопись и счётчики — переучивать их на словарь поверхностей значило бы
    развезти одно знание по четырём местам."""
    vals = set(sfmap.values())
    for st in SURFACE_STATES:
        if st in vals:
            return st
    return fallback


def surface_summary(sfmap: dict) -> list:
    """[(состояние, «MO»)] по тяжести — общая основа для летописи, печатной
    формы и выгрузки: три текста об одном, собранные по-разному, разойдутся."""
    out = []
    for st in SURFACE_STATES:
        letters = "".join(k for k in SURFACE_ORDER if sfmap.get(k) == st)
        if letters:
            out.append((st, letters))
    return out


def _as_map(state: str, surfaces) -> dict:
    """Аргумент `surfaces` принимается И строкой, И словарём.

    Строка — прежний вызов «эти поверхности в состоянии зуба», словарь — новый
    «у каждой своё». Две сигнатуры вместо одной завели бы два пути отрисовки, а
    их и так уже два (лицевой и сверху)."""
    if isinstance(surfaces, dict):
        return {k: v for k, v in surfaces.items()
                if k in SURFACE_ORDER and v in SURFACE_STATES}
    return surface_map(state, surfaces or "")


def tooth_svg(fdi: int, state: str = "ok", *, width: int = 44,
              interactive: bool = False, extra_class: str = "",
              surfaces="", marks=()) -> str:
    """Готовый <svg> одного зуба. Всё рисование — в канонической ориентации,
    верхняя челюсть переворачивается обёрткой."""
    state = state if state in STATE_RO else "ok"
    col = COLORS.get(state, LINE)
    fill = FILLS.get(state, "#FFFFFF")
    h = int(width * VB_H / VB_W)
    body: list[str] = []

    crown = crown_path(fdi)
    roots = root_paths(fdi)
    gid = f"dpg-{fdi}-{state}"
    defs = ""
    # ⚠️ Ореол — по КОРОНКЕ, не по всему силуэту: корни у импланта заменены
    # винтом, и ободок по несуществующему корню висел бы в воздухе. Коронку
    # рисуют ВСЕ состояния, включая призрак «lipsă», — отметка видна всегда.
    # ⚠️ Кладётся первым: корни и коронка идут после и закрывают внутреннюю
    # половину ободка, наружу выходит ровно рант.
    body.extend(_mark_halo(crown, marks))

    if state == "lipsa":
        # «отсутствует» — только призрак контура, пунктиром
        body.append(f"<path d='{crown}' fill='none' stroke='{COLORS['lipsa']}' "
                    f"stroke-width='1.6' stroke-dasharray='3 3'/>")
        for r in roots:
            body.append(f"<path d='{r}' fill='none' stroke='{COLORS['lipsa']}' "
                        f"stroke-width='1.6' stroke-dasharray='3 3'/>")
    elif state == "implant":
        screw, threads = _implant_screw(fdi)
        body.append(f"<path d='{screw}' fill='{fill}' stroke='{col}' stroke-width='1.8'/>")
        for t in threads:
            body.append(f"<path d='{t}' fill='none' stroke='{col}' stroke-width='1.4' "
                        f"opacity='.75'/>")
        defs = _enamel_defs(gid, ENAMEL)
        body.append(f"<path d='{crown}' fill='url(#{gid})' stroke='{col}' "
                    f"stroke-width='1.8'/>")
        for f in _fissures(fdi):
            body.append(f"<path d='{f}' fill='none' stroke='{col}' stroke-width='1.2' opacity='.5'/>")
    else:
        root_col = col if state == "extras" else LINE
        for r in roots:
            body.append(f"<path d='{r}' fill='{fill if state == 'extras' else ROOT_FILL}' "
                        f"stroke='{root_col}' stroke-width='1.8'/>")
        crown_fill, crown_col = f"url(#{gid})", LINE
        defs = _enamel_defs(gid, ENAMEL)
        if state == "coroana":
            crown_col = "#D97706"
            defs = _enamel_defs(gid, CROWN_GOLD)
        elif state == "extras":
            # удалённый зуб — не эмаль, а след от неё: плоская серая заливка
            crown_fill, crown_col, defs = FILLS["extras"], col, ""
        elif state in ("carie", "obturatie"):
            crown_col = col
        body.append(f"<path d='{crown}' fill='{crown_fill}' stroke='{crown_col}' "
                    f"stroke-width='1.8'/>")

        if state != "coroana":
            det = crown_col if state in ("carie", "obturatie") else LINE_SOFT
            for f in _fissures(fdi):
                body.append(f"<path d='{f}' fill='none' stroke='{det}' stroke-width='1.2' "
                            f"opacity='.55'/>")
        # поверхности отмечены — метки идут по НИМ; не отмечены (и в легенде,
        # где зуб рисуется без пациента) — прежнее пятно по центру коронки
        # ⚠️ Имя НЕ `marks`: так звался этот список до 08-17, а теперь `marks` —
        # аргумент функции (отметки зуба). Затирание сошло бы с рук молча:
        # ореол уже нарисован выше, и падать было бы нечему
        sf_marks = _surface_marks(fdi, _as_map(state, surfaces))
        if sf_marks:
            body.extend(sf_marks)
        elif state == "carie":
            k = _width_k(fdi)
            body.append(f"<path d='M {_p(_sx(18, k), 16)} Q {_p(_sx(22, k), 10, _sx(26, k), 16)} "
                        f"Q {_p(_sx(28, k), 22, _sx(22, k), 25)} "
                        f"Q {_p(_sx(16, k), 22, _sx(18, k), 16)} Z' fill='{col}'/>")
        elif state == "obturatie":
            k = _width_k(fdi)
            body.append(f"<path d='M {_p(_sx(16.5, k), 15)} Q {_p(_sx(22, k), 11, _sx(27.5, k), 15)} "
                        f"Q {_p(_sx(29, k), 21, _sx(22, k), 23.5)} "
                        f"Q {_p(_sx(15, k), 21, _sx(16.5, k), 15)} Z' fill='{col}'/>")
        elif state == "extras":
            # крест «удалён» — по ширине КОНКРЕТНОГО зуба: у молочного бокового
            # резца (k=0.66) фиксированные 12…32 вылезали за коронку.
            # k считается ЗДЕСЬ: соседние ветки заводят его каждая себе, и
            # в этой его не было — страница фиши падала на легенде состояний
            k = _width_k(fdi)
            # крест лежит на КОРОНКЕ (15..43), а не поперёк всего зуба: поверх
            # трёх расходящихся корней он читался клубком линий, а не знаком.
            # Полуширина — от класса: на моляре крест шириной с резец теряется
            hw = _MARK_DX.get(tooth_class(fdi), 7.0) + 1.0
            body.append(f"<path d='M {_p(_sx(22 - hw, k), 15)} L {_p(_sx(22 + hw, k), 43)} "
                        f"M {_p(_sx(22 + hw, k), 15)} L {_p(_sx(22 - hw, k), 43)}' "
                        f"stroke='{col}' stroke-width='3' stroke-linecap='round'/>")

    inner = "".join(body)
    if mirrored(fdi):                       # мезиальная сторона слева
        inner = f"<g transform='translate({VB_W},0) scale(-1,1)'>{inner}</g>"
    if is_upper(fdi):                       # верхняя дуга смотрит вниз
        inner = f"<g transform='translate(0,{VB_H}) scale(1,-1)'>{inner}</g>"
    # ⚠️ <defs> ВНЕ перевёрнутой группы: внутри неё он тоже сработал бы, но
    # определение — не рисунок, и место ему у корня тега, а не в трансформации
    inner = defs + inner

    # состояние уезжает КЛАССОМ: оформление зуба живёт в panel.css (тень,
    # наведение), и без класса CSS не отличит призрак «lipsa» от живого зуба —
    # тень под отсутствующим зубом выглядит как ошибка вёрстки
    cls = (f"tooth-svg tooth-{state}" + (" tooth-int" if interactive else "")
           + (f" {extra_class}" if extra_class else ""))
    return (f"<svg class='{cls}' viewBox='0 0 {VB_W:.0f} {VB_H:.0f}' width='{width}' "
            f"height='{h}' fill='none' stroke-linecap='round' stroke-linejoin='round' "
            f"aria-label='{fdi}'>{inner}</svg>")


