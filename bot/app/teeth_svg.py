def _enamel_defs(gid: str, stops: tuple) -> str:
    """Градиент эмали. Ось чуть наклонная (не строго сверху вниз): вертикальный
    переход читается цилиндром, наклонный — телом со светом сбоку.

    ⭐ Координаты в долях РАМКИ САМОЙ КОРОНКИ (objectBoundingBox), поэтому один
    и тот же градиент годится и резцу, и моляру, и переворот верхней дуги несёт
    его с собой: свет остаётся у жевательного края обеих челюстей."""
    top, mid, low = stops
    return (f"<defs><linearGradient id='{gid}' x1='.25' y1='0' x2='.75' y2='1'>"
            f"<stop offset='0' stop-color='{top}'/>"
            f"<stop offset='.52' stop-color='{mid}'/>"
            f"<stop offset='1' stop-color='{low}'/></linearGradient></defs>")


def _surface_marks(fdi: int, sfmap: dict) -> list[str]:
    """Метка на КАЖДОЙ отмеченной поверхности, на своём месте коронки.

    Поверхности регистратура отмечает с 08-06, но рисунок про них молчал:
    в карте стояло «MO», а на зубе всё равно горела одна точка по центру —
    картинка знала меньше, чем запись под ней.

    ⚠️ Проекция ЛИЦЕВАЯ, и язычной поверхности в ней физически не видно.
    Поэтому L — кольцо, а не пятно: «отмечено, но с той стороны». Врать
    заливкой на месте, которого не видно, нельзя — по такому рисунку читают
    диагноз.
    """
    cls = tooth_class(fdi)
    k = _width_k(fdi)
    dx = _MARK_DX.get(cls, 7.0)
    # мезиальная сторона в каноне ВСЕГДА справа — сторону выбирает зеркало
    # обёртки, здесь ветвления по квадранту быть не должно
    r = 3.1 * k
    # ⚠️ Жевательная метка садится ГЛУБЖЕ у боковых зубов: у моляра кромка
    # изрезана буграми (низ фиссуры на 15), и метка на «краю» вылезала из
    # контура наружу — на кадре это читается как пятно рядом с зубом.
    oy = 13.0 if cls in ("incisor_c", "incisor_l", "canine") else 19.0
    pos = {
        "O": (22.0, oy),
        "V": (22.0, 28.0),
        "L": (22.0, 36.0),
        "M": (22.0 + dx, 27.0),
        "D": (22.0 - dx, 27.0),
    }
    out = []
    # ⚠️ Цвет берётся у САМОЙ поверхности, а не у зуба: на одном моляре бывает
    # кариес мезиально и пломба окклюзионно, и один цвет на все метки сказал бы
    # неправду ровно про ту поверхность, ради которой их и рисуют
    for letter in SURFACE_ORDER:
        st = sfmap.get(letter)
        if st is None or letter not in pos:
            continue
        col, fill = COLORS.get(st, LINE), MARK_FILL.get(st, LINE)
        x, yy = pos[letter]
        cx = _sx(x, k)
        if letter == "L":
            out.append(f"<circle cx='{cx:.1f}' cy='{yy:.1f}' r='{r:.1f}' "
                       f"fill='none' stroke='{col}' stroke-width='1.6'/>")
        else:
            out.append(f"<circle cx='{cx:.1f}' cy='{yy:.1f}' r='{r:.1f}' "
                       f"fill='{fill}' stroke='{col}' stroke-width='1.3'/>")
    return out


def _implant_screw(fdi: int) -> str:
    """Резьбовой имплант вместо корня: ствол + витки."""
    k = _width_k(fdi)
    s = lambda x: _sx(x, k)  # noqa: E731
    body = (f"M {_p(s(16), 40)} L {_p(s(18.5), _ry(88))} Q {_p(s(22), _ry(95), s(25.5), _ry(88))} "
            f"L {_p(s(28), 40)} Z")
    threads = []
    for i in range(6):
        yy = _ry(46 + i * 8)
        half = 5.8 - i * 0.5
        threads.append(f"M {_p(s(22 - half), yy)} L {_p(s(22 + half), yy + 1.8)}")
    return body, threads


# ------------------------------------------------------- вид сверху (окклюзионный)
#
# Зачем он вообще. Поверхности зуба клиника отмечает буквами MODVL, но в
# ЛИЦЕВОЙ проекции язычной стороны не видно физически, а жевательная сжата в
# кромку — метки там стоят условно, и L приходится рисовать кольцом «отмечено,
# но с той стороны». Сверху все пять поверхностей лежат каждая на своём месте,
# поэтому карие на мезиальной и карие на дистальной — два разных рисунка, а не
# одна точка с подписью.
#
# ⚠️ ПЕРЕВОРАЧИВАЕТСЯ ЗДЕСЬ ДРУГАЯ ЧЕЛЮСТЬ, чем в лицевом виде. Канон здесь —
# щёчная сторона ВВЕРХУ. Верхний ряд рисуется как есть (его нёбо смотрит вниз,
# к середине карточки), нижний переворачивается (его язычная — вверх, тоже к
# середине). В лицевом виде правило обратное (`is_upper` → переворот), и
# скопировать его сюда — значит нарисовать обе дуги щеками внутрь: ошибка ничем
# себя не выдаёт, рисунок остаётся «красивым зубом», просто мезиальная карие
# показывается на дистальной стороне.

VB_O = 44.0
OCC_C = VB_O / 2

# Ширина (мезио-дистальная) — ТА ЖЕ, что в лицевом виде: один зуб не может быть
# разной ширины на двух картинках одной карточки. Отсюда база = размах контура
# коронки, а множитель — общий `_width_k`.
_MD_BASE = {"incisor_c": 19.4, "incisor_l": 19.4, "canine": 21.0,
            "premolar": 25.0, "molar": 33.0}
# Глубина к ширине. Числа — от вестибуло-язычных размеров: верхний резец ШИРЕ,
# чем глубок (0.84), верхний премоляр наоборот (1.27). Без этого весь ряд
# выходит одинаковыми кружками, и вид сверху перестаёт что-либо различать.
_BL_K = {("incisor_c", True): 0.84, ("incisor_c", False): 1.13,
         ("incisor_l", True): 0.96, ("incisor_l", False): 1.10,
         ("canine", True): 1.06, ("canine", False): 1.08,
         ("premolar", True): 1.27, ("premolar", False): 1.07,
         ("molar", True): 1.05, ("molar", False): 0.96}


# Сверху коронке не нужно место под корни, поэтому она занимает рамку плотнее,
# чем в лицевом виде. Это НЕ вторая система ширин: множитель один на все зубы,
# соотношения внутри ряда остаются те же.
OCC_ZOOM = 1.10


def occ_half(fdi: int) -> tuple:
    """Полуширина и полуглубина коронки сверху."""
    cls = tooth_class(fdi)
    hw = _MD_BASE[cls] * _width_k(fdi) * OCC_ZOOM / 2
    return hw, hw * _BL_K[(cls, is_upper(fdi))]


def occ_lobes(fdi: int) -> list:
    """Бугры как ДОЛЬКИ: [(x, y, rx, ry)] в каноне (мезиальная сторона справа).

    ⭐ Это второй заход на анатомию сверху, и он другой по устройству. Первый
    резал КОНТУР выемками, оставляя борозды линиями, — моляр получался
    раскрытой книгой. Здесь наоборот: под всей коронкой лежит тёмный тон, а
    поверх него округлые дольки светлее. Борозды не рисуются вовсе — это
    ЗАЗОРЫ между дольками, ровно как на настоящей жевательной поверхности.
    Отсюда и силуэт: он собирается сам и не спорит с рисунком внутри.

    Число бугров — морфология, а не вкус: у верхнего моляра четыре (нёбные
    крупнее щёчных), у нижнего пять (третий щёчный — дистальный, мельче), у
    премоляра два, у клыка один со смещением мезиально, у резца режущий валик
    и язычный бугорок.
    """
    cls = tooth_class(fdi)
    hw, hd = occ_half(fdi)
    cx = cy = OCC_C
    if cls == "molar":
        by, ly = cy - hd * 0.44, cy + hd * 0.42
        if is_upper(fdi):
            return [(cx + hw * 0.44, by, hw * 0.46, hd * 0.44),
                    (cx - hw * 0.44, by, hw * 0.44, hd * 0.42),
                    (cx + hw * 0.40, ly, hw * 0.48, hd * 0.46),
                    (cx - hw * 0.44, ly, hw * 0.40, hd * 0.40)]
        return [(cx + hw * 0.52, by, hw * 0.38, hd * 0.44),
                (cx, by, hw * 0.36, hd * 0.43),
                (cx - hw * 0.52, by, hw * 0.34, hd * 0.38),
                (cx + hw * 0.40, ly, hw * 0.44, hd * 0.44),
                (cx - hw * 0.42, ly, hw * 0.42, hd * 0.42)]
    if cls == "premolar":
        return [(cx, cy - hd * 0.40, hw * 0.80, hd * 0.46),
                (cx, cy + hd * 0.42, hw * 0.68, hd * 0.42)]
    if cls == "canine":
        return [(cx + hw * 0.14, cy - hd * 0.10, hw * 0.76, hd * 0.66)]
    # резец: режущий валик вдоль щёчного края + язычный бугорок
    return [(cx, cy - hd * 0.42, hw * 0.86, hd * 0.40),
            (cx, cy + hd * 0.36, hw * 0.62, hd * 0.46)]


def occ_outline(fdi: int) -> str:
    """Контур жевательной поверхности: резец — плоский режущий край и округлый
    язычный бугорок, клык — остриё в щёчную сторону, премоляр — овал, моляр —
    скруглённый прямоугольник."""
    cls = tooth_class(fdi)
    hw, hd = occ_half(fdi)
    cx = cy = OCC_C

    if cls in ("incisor_c", "incisor_l"):
        return (f"M {_p(cx - hw, cy - hd * 0.35)} "
                f"Q {_p(cx - hw, cy - hd, cx - hw * 0.62, cy - hd)} "
                f"L {_p(cx + hw * 0.62, cy - hd)} "
                f"Q {_p(cx + hw, cy - hd, cx + hw, cy - hd * 0.35)} "
                f"C {_p(cx + hw, cy + hd * 0.45, cx + hw * 0.55, cy + hd, cx, cy + hd)} "
                f"C {_p(cx - hw * 0.55, cy + hd, cx - hw, cy + hd * 0.45, cx - hw, cy - hd * 0.35)} Z")
    if cls == "canine":
        return (f"M {_p(cx - hw, cy + hd * 0.15)} "
                f"Q {_p(cx - hw * 0.85, cy - hd * 0.65, cx, cy - hd)} "
                f"Q {_p(cx + hw * 0.85, cy - hd * 0.65, cx + hw, cy + hd * 0.15)} "
                f"Q {_p(cx + hw * 0.72, cy + hd, cx, cy + hd)} "
                f"Q {_p(cx - hw * 0.72, cy + hd, cx - hw, cy + hd * 0.15)} Z")
    if cls == "premolar":
        return (f"M {_p(cx - hw, cy)} "
                f"C {_p(cx - hw, cy - hd * 0.72, cx - hw * 0.68, cy - hd, cx, cy - hd)} "
                f"C {_p(cx + hw * 0.68, cy - hd, cx + hw, cy - hd * 0.72, cx + hw, cy)} "
                f"C {_p(cx + hw * 0.92, cy + hd * 0.72, cx + hw * 0.6, cy + hd, cx, cy + hd)} "
                f"C {_p(cx - hw * 0.6, cy + hd, cx - hw * 0.92, cy + hd * 0.72, cx - hw, cy)} Z")
    # ⛔ Зубчатый край (выемки между буграми) ПРОБОВАЛСЯ 08-16 и отвергнут по
    # кадру: вместе с вертикальной бороздой и симметричной выемкой сверху и
    # снизу моляр начинал читаться РАСКРЫТОЙ КНИГОЙ, а не зубом. На 41 px
    # анатомия края не различима вовсе, а ложное сходство — различимо сразу.
    # Бугры показывают ДОЛЬКИ (occ_lobes), край остаётся спокойным.
    r = min(hw, hd) * 0.36
    return (f"M {_p(cx - hw + r, cy - hd)} L {_p(cx + hw - r, cy - hd)} "
            f"Q {_p(cx + hw, cy - hd, cx + hw, cy - hd + r)} "
            f"L {_p(cx + hw, cy + hd - r)} "
            f"Q {_p(cx + hw, cy + hd, cx + hw - r, cy + hd)} "
            f"L {_p(cx - hw + r, cy + hd)} "
            f"Q {_p(cx - hw, cy + hd, cx - hw, cy + hd - r)} "
            f"L {_p(cx - hw, cy - hd + r)} "
            f"Q {_p(cx - hw, cy - hd, cx - hw + r, cy - hd)} Z")


def _occ_fissures(fdi: int) -> list:
    """Язычный бугорок резца и продольный валик клыка.

    У боковых зубов рельеф рисуют ДОЛЬКИ (occ_lobes) и зазоры между ними;
    у передних долек всего две, и зазор между ними ничего не сказал бы —
    там нужна линия."""
    cls = tooth_class(fdi)
    hw, hd = occ_half(fdi)
    cx = cy = OCC_C
    if cls in ("incisor_c", "incisor_l", "canine"):
        out = [f"M {_p(cx - hw * 0.5, cy + hd * 0.45)} "
               f"Q {_p(cx, cy + hd * 0.12, cx + hw * 0.5, cy + hd * 0.45)}"]
        if cls == "canine":
            out.append(f"M {_p(cx, cy - hd * 0.72)} L {_p(cx, cy + hd * 0.2)}")
        return out
    # ⛔ Веток для премоляра и моляра здесь БОЛЬШЕ НЕТ. С переходом на дольки
    # (occ_lobes) борозды боковых зубов рисуют зазоры между буграми, и эта
    # функция для них не вызывается. Оставленный «на всякий случай» расчёт был
    # бы мёртвым кодом, который выглядит действующим, — ровно та беда, что
    # случилась с копией ODONTO_CSS.
    return []


def occ_zones(fdi: int) -> dict:
    """Пять полей поверхностей: щёчное, язычное, мезиальное, дистальное и
    жевательное по центру.

    ⭐ Прямоугольники нарочно с запасом ЗА контур — их режет обтравка самим
    контуром. Иначе поле пришлось бы пересчитывать под каждый класс отдельно,
    и любая правка формы зуба молча оставляла бы щель между полем и краем."""
    hw, hd = occ_half(fdi)
    ow, oh = hw * 0.44, hd * 0.40
    c = OCC_C
    return {"V": (0.0, 0.0, VB_O, c - oh),
            "L": (0.0, c + oh, VB_O, VB_O - (c + oh)),
            "M": (c + ow, c - oh, VB_O - (c + ow), oh * 2),
            "D": (0.0, c - oh, c - ow, oh * 2),
            "O": (c - ow, c - oh, ow * 2, oh * 2)}


def _occ_wrap(fdi: int, state: str, defs: str, body: list, width: int,
              interactive: bool, extra_class: str) -> str:
    inner = "".join(body)
    if mirrored(fdi):          # мезиальная сторона слева
        inner = f"<g transform='translate({VB_O},0) scale(-1,1)'>{inner}</g>"
    if not is_upper(fdi):      # ⚠️ переворачивается НИЖНЯЯ дуга, см. шапку раздела
        inner = f"<g transform='translate(0,{VB_O}) scale(1,-1)'>{inner}</g>"
    cls = (f"tooth-svg tooth-occ tooth-{state}"
           + (" tooth-int" if interactive else "")
           + (f" {extra_class}" if extra_class else ""))
    return (f"<svg class='{cls}' viewBox='0 0 {VB_O:.0f} {VB_O:.0f}' width='{width}' "
            f"height='{width}' fill='none' stroke-linecap='round' "
            f"stroke-linejoin='round' aria-label='{fdi}'><defs>{defs}</defs>{inner}</svg>")


def occlusal_svg(fdi: int, state: str = "ok", *, width: int = 44,
                 interactive: bool = False, extra_class: str = "",
                 surfaces="", marks=()) -> str:
    """Готовый <svg> зуба СВЕРХУ. Рамка квадратная: жевательная поверхность
    примерно так же глубока, как широка, и вытянутая рамка лицевого вида тут
    оставила бы половину пустой."""
    state = state if state in STATE_RO else "ok"
    col = COLORS.get(state, LINE)
    gid, cid = f"dpo-{fdi}-{state}", f"dpc-{fdi}-{state}"
    outline = occ_outline(fdi)
    hw, hd = occ_half(fdi)
    cx = cy = OCC_C
    defs = f"<clipPath id='{cid}'><path d='{outline}'/></clipPath>"
    body: list = []
    # ⚠️ ДО ветки «lipsă»: она уходит из функции своим return, и ореол,
    # добавленный ниже, у отсутствующего зуба просто не нарисовался бы —
    # молча, потому что состояние и отметка теперь независимы
    body.extend(_mark_halo(outline, marks))

    if state == "lipsa":
        body.append(f"<path d='{outline}' fill='none' stroke='{COLORS['lipsa']}' "
                    f"stroke-width='1.6' stroke-dasharray='3 3'/>")
        return _occ_wrap(fdi, state, defs, body, width, interactive, extra_class)

    if state == "coroana":
        defs += _enamel_defs(gid, CROWN_GOLD)
        fill, line = CROWN_GOLD[2], "#D97706"
    elif state == "extras":
        fill, line = FILLS["extras"], col
    else:
        defs += _enamel_defs(gid, ENAMEL)
        # ⚠️ Подложка — САМЫЙ ТЁМНЫЙ тон, а не градиент: именно она видна в
        # зазорах между дольками и работает бороздой. Поставь сюда градиент —
        # и борозды исчезнут, поверхность станет плоской заливкой
        fill = ENAMEL[2]
        line = col if state in ("carie", "obturatie", "implant") else LINE
    body.append(f"<path d='{outline}' fill='{fill}'/>")

    # ⚠️ Дольки бугров — СРАЗУ после подложки и ДО цветных полей. Нарисованные
    # после, они закрывают собой отметку поверхности, и «кариес мезиально»
    # остаётся видным только в зазорах между буграми: цвет на месте, но его
    # почти нет. Подложка при этом самый тёмный тон — она и есть борозда.
    if state not in ("lipsa", "extras", "implant"):
        lobe = (f"{CROWN_GOLD[0]}" if state == "coroana" else f"url(#{gid})")
        for lx, ly, rx, ry in occ_lobes(fdi):
            body.append(f"<ellipse cx='{lx:.1f}' cy='{ly:.1f}' rx='{rx:.1f}' "
                        f"ry='{ry:.1f}' fill='{lobe}'/>")

    # поверхности: отмеченные поля заливаются разбавленным цветом состояния.
    # ⚠️ Ничего не отмечено — бледный оттенок на ВСЮ коронку, а не пятно по
    # центру: «поверхность не указана» — это не «поражена центральная».
    # ⚠️ Пускает сюда СПИСОК СОСТОЯНИЙ, а не палитра: `state in MARK_FILL`
    # читается так же, но полярность у него обратная — третье поверхностное
    # состояние не уронило бы ничего, а просто перестало бы рисоваться, и ни
    # одна проверка не покраснела бы (грабля карты про PLAN_ACTIVE). Цвет по
    # той же причине берётся через `.get`: гейт спрашивает про состояние ЗУБА,
    # а ключ здесь — состояние ПОВЕРХНОСТИ, и на смеси они РАЗНЫЕ.
    if state in SURFACE_STATES:
        sfmap = _as_map(state, surfaces)
        if sfmap:
            zones = occ_zones(fdi)
            cells = "".join(
                f"<rect x='{zones[ln][0]:.1f}' y='{zones[ln][1]:.1f}' "
                f"width='{zones[ln][2]:.1f}' height='{zones[ln][3]:.1f}' "
                f"fill='{MARK_FILL.get(sfmap[ln], LINE)}' fill-opacity='.82'/>"
                for ln in SURFACE_ORDER if ln in sfmap)
            body.append(f"<g clip-path='url(#{cid})'>{cells}</g>")
        else:
            body.append(f"<path d='{outline}' fill='{FILLS[state]}'/>")

    if state == "implant":
        r = min(hw, hd) * 0.72
        body.append(f"<circle cx='{cx:.1f}' cy='{cy:.1f}' r='{r:.1f}' "
                    f"fill='{FILLS['implant']}' stroke='{col}' stroke-width='1.6'/>")
        body.append(f"<circle cx='{cx:.1f}' cy='{cy:.1f}' r='{r * 0.46:.1f}' "
                    f"fill='none' stroke='{col}' stroke-width='1.4'/>")
    elif state != "coroana" and tooth_class(fdi) in ("incisor_c", "incisor_l",
                                                     "canine"):
        # ⛔ У боковых зубов линий борозд БОЛЬШЕ НЕТ: их рисуют зазоры между
        # дольками. Вернуть линии поверх долек — значит получить и то, и другое
        # разом, а это уже не поверхность, а штриховка
        det = col if state in ("carie", "obturatie") else LINE_SOFT
        for f in _occ_fissures(fdi):
            body.append(f"<path d='{f}' fill='none' stroke='{det}' stroke-width='1.2' "
                        f"opacity='.55'/>")

    if state == "extras":
        body.append(f"<path d='M {_p(cx - hw * 0.62, cy - hd * 0.62)} "
                    f"L {_p(cx + hw * 0.62, cy + hd * 0.62)} "
                    f"M {_p(cx + hw * 0.62, cy - hd * 0.62)} "
                    f"L {_p(cx - hw * 0.62, cy + hd * 0.62)}' "
                    f"stroke='{col}' stroke-width='3' stroke-linecap='round'/>")

    # ⛔ Внутреннего канта здесь НЕТ намеренно. Сжатая копия контура задумывалась
    # как толщина эмали, а на кадре дала ВТОРОЙ контур: светлая линия вдоль
    # выемки читается корешком, и моляр превращается в раскрытую книгу. Глубину
    # даёт градиент, а край — одна обводка.
    body.append(f"<path d='{outline}' fill='none' stroke='{line}' stroke-width='1.8'/>")
    return _occ_wrap(fdi, state, defs, body, width, interactive, extra_class)


