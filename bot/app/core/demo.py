"""Демо-режим (`DENTART_DEMO=1`): живое демо программы с сайта (01.10).

Программа стоит за шлюзом `demo/gate.py`: каждому посетителю сайта — своя
копия демо-клиники на срок шлюза (DEMO_TTL_MIN), потом сброс. Это та же настольная сборка кода
(SQLite, вход по ADMIN_KEY — ключ знает шлюз, а не посетитель), и флаг
убирает из неё ровно то, что меняет МАШИНУ или УЧЁТКИ: обновление, ключ
картотеки, копию и восстановление, PIN и пользователей, лицензию, токен бота,
сеть клиники. Всё остальное — журнал, фиша, одонтограмма, настройки клиники
— работает как у клиники: в этом и смысл демо.

⛔ Здесь НЕТ ветки «кто это». Демо входит обычным ключом, и `current_user`
остаётся без исключений: флаг, по ошибке попавший в `dental.env` клиники, не
открыл бы журнал никому — он только спрятал бы несколько экранов.

⭐ Флаг читается из ОКРУЖЕНИЯ процесса, не из `clinic.json`: профиль
демо-клиники посетитель правит сам (это тоже демо), и выключить защиту
правкой профиля он не должен. ⛔ И только у НЕсобранной программы: лаунчер
копирует в окружение все строки `dental.env` подряд, и одна строка в
текстовом файле клиники иначе спрятала бы ей обновление и копию — то же
правило, что у `DENTART_MODE` (docs/dentpilot-2/deployment-modes.md). Демо
живёт из исходников в контейнере, ему это не мешает.

`BLOCKED` — префиксы адресов, которых в демо нет. Список с ПОЛЯРНОСТЬЮ
«включает запрет» (прайор из карты): переименованный маршрут делает строку
пустой, и запрет исчезает молча. Поэтому `test_structure` сверяет каждую
строку с живыми маршрутами — строка, под которую не подходит ни один адрес,
краснеет. Новый опасный маршрут дописывается сюда руками; «всё, кроме белого
списка» было бы длиннее и гнило бы с каждым новым экраном настроек.

Адреса `/demo/…` (сброс копии, состояние пула) обслуживает ШЛЮЗ, программа о
них не знает: ссылка «Începe din nou» в баннере ведёт туда.
"""
import os

from .. import paths

BLOCKED = (
    # обновление: GitHub, реестр Windows, перезапуск
    "/admin/settings/system", "/admin/update/", "/api/settings/system",
    # ключ картотеки (DPAPI) и режим восстановления
    "/admin/settings/crypt", "/admin/recover", "/api/settings/crypt",
    # копия и восстановление из копии
    "/admin/settings/backup", "/admin/backup/", "/api/settings/backup",
    # учётки и PIN
    "/admin/settings/security", "/admin/users/", "/admin/pin/", "/admin/setup",
    "/api/settings/security", "/api/settings/users", "/api/settings/pin",
    # токен бота: чужой токен запустил бы polling с демо-сервера
    "/admin/settings/telegram", "/admin/telegram/",
    # сеть машины и брандмауэр
    "/admin/settings/lan", "/admin/lan/", "/api/settings/lan",
    # лицензия и раздвоение картотеки
    "/admin/license", "/api/license", "/admin/migration",
)

# Загрузка файла в демо — до 8 МБ (у клиники 25): копия живёт час, а место на
# демо-сервере общее на всех посетителей.
BODY_CAP = 8 * 1024 * 1024


def on() -> bool:
    if paths.is_frozen():
        return False
    return os.environ.get("DENTART_DEMO", "").strip().strip("\"'").lower() in ("1", "true", "yes")


def ttl_text() -> str:
    """Сколько живёт копия — словами шлюза (`DENTART_DEMO_TTL`, demo/words.py):
    срок держит шлюз, программа его не считает, а называет в полосе демо.
    Без шлюза (прогон, песочница) — «o oră»."""
    return os.environ.get("DENTART_DEMO_TTL", "").strip() or "o oră"


def refuses(path: str) -> bool:
    """Адреса нет в демо: сам префикс или что-то под ним («/admin/license»
    закрывает и «/admin/license/request», но не «/admin/licenses»)."""
    if not on():
        return False
    for p in BLOCKED:
        head = p if p.endswith("/") else p + "/"
        if path == p or path.startswith(head):
            return True
    return False
