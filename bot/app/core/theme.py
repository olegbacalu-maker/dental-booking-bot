"""Фирменный вид клиники: цвет, стиль оформления, логотип.

Одна установка — одна клиника (база и профиль лежат рядом с exe), поэтому тема
живёт там же, где остальной профиль: секцией `theme` в `clinic.json`. Отдельной
таблицы в базе у неё нет намеренно — тема это ПРОФИЛЬ, а не данные пациентов:
её увозят вместе с `clinic.json`, когда клинику переносят на новый ПК, и она
не имеет права попасть в выгрузку по закону 195.

Что здесь есть и почему именно здесь:

⭐ **Цвет клиники доезжает до CSS** — то есть строка из формы попадает в таблицу
   стилей. «Просто подставить» её нельзя: `#fff}body{display:none` погасил бы
   журнал, а `url(https://…)` увёл бы запрос наружу с чужой страницы. Поэтому
   в CSS не попадает НИ ОДИН символ, введённый человеком: цвет разбирается в
   три числа и собирается обратно нашим же форматом. Мусор не экранируется — он
   отвергается, и берётся фирменный зелёный. Прайор тот же, что у `innerHTML`
   08-08: экранирование спасает только там, где угадан контекст, а отказ от
   чужой строки — везде.

⭐ **Оттенки вычисляются, а не спрашиваются.** У клиники один вопрос — «какой у
   нас цвет». Интерфейсу нужно шесть значений: наведение, текст, подложка,
   кромка, кольцо фокуса, свечение кнопки. Спросить шесть — это тот самый
   конструктор CSS, вместо которого мы и делаем три стиля; вычислить — держать
   их согласованными по определению.

⭐ **Тёмный вариант подбирается ПО КОНТРАСТУ, а не «минус 20% яркости».** Цвет
   выбирает директор, и светло-оранжевый — законный выбор: от него нужен
   читаемый текст, а не бледная полоска на белом. Тот же расчёт решает, каким
   цветом писать НА фирменной кнопке.

⚠️ Чего здесь нет: разбора самой картинки. В `.venv-desktop` не ставят лишнего
   (это окружение сборки, всё уедет в exe), Pillow там нет и не будет. Логотип
   поэтому проверяется по сигнатуре файла и по размеру, а геометрию ограничивает
   CSS. Отсюда же запрет на SVG: он не картинка, а документ со скриптами внутри.
"""
