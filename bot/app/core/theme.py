# Тёмный текст интерфейса — тот же --text, что в panel.css. Нужен здесь как
# ЧИСЛО: по нему считается, чем писать на фирменной кнопке.
_TEXT_DARK = (0x16, 0x20, 0x33)
_WHITE = (0xFF, 0xFF, 0xFF)
_BLACK = (0x00, 0x00, 0x00)

_HEX_RE = re.compile(r"#?([0-9a-fA-F]{6})\Z")


# ---------- цвет: разбор, сборка, арифметика ----------

def parse_hex(value) -> tuple[int, int, int] | None:
    """Строка → три числа. `None` на всё, что не ровно шесть шестнадцатеричных
    цифр: сокращение `#fff`, имя `red`, `rgb(...)` и любой мусор из формы.

    ⭐ Это и есть вся защита от подстановки в CSS. Дальше по коду наружу уходит
    только результат `to_hex()` — строка, собранная НАМИ из трёх чисел."""
    if not isinstance(value, str):
        return None
    m = _HEX_RE.match(value.strip())
    if not m:
        return None
    h = m.group(1)
    return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)


def to_hex(rgb: tuple[int, int, int]) -> str:
    return "#%02X%02X%02X" % rgb


def _linear(c: int) -> float:
    x = c / 255
    return x / 12.92 if x <= 0.03928 else ((x + 0.055) / 1.055) ** 2.4


def luminance(rgb: tuple[int, int, int]) -> float:
    r, g, b = (_linear(c) for c in rgb)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast(a: tuple[int, int, int], b: tuple[int, int, int]) -> float:
    """Отношение контраста по WCAG: 1 — цвета совпали, 21 — чёрное на белом."""
    la, lb = luminance(a), luminance(b)
    lo, hi = sorted((la, lb))
    return (hi + 0.05) / (lo + 0.05)


def _mix(a: tuple[int, int, int], b: tuple[int, int, int],
         k: float) -> tuple[int, int, int]:
    """`k` — доля второго цвета."""
    return tuple(round(x + (y - x) * k) for x, y in zip(a, b))   # type: ignore[return-value]


# ---------- палитра ----------

@functools.lru_cache(maxsize=32)
def palette(primary: str, style: str) -> dict[str, str]:
    """Шесть производных значений из одного фирменного цвета.

    Кешируется по (цвет, стиль): считается на КАЖДОЙ отрисовке страницы, а
    журнал перерисовывается раз в 12 секунд на каждом открытом экране."""
    rgb = parse_hex(primary) or parse_hex(DEFAULT_PRIMARY)
    assert rgb is not None                      # DEFAULT_PRIMARY разбирается всегда
    # стиль тоже приводится ЗДЕСЬ, а не только у вызывающего: тёмный оттенок
    # подбирается по фону, и незнакомое имя обязано дать палитру, а не KeyError
    bg = parse_hex(STYLES.get(style, STYLES[DEFAULT_STYLE])["--bg"]) or _WHITE

    # Тёмный (наведение + текст ссылок и заголовка). Сначала обязательный шаг
    # вниз — иначе у тёмного фирменного цвета наведение было бы неотличимо от
    # покоя; дальше дотемняем, пока текст не станет читаемым на фоне.
    dark = _mix(rgb, _BLACK, 0.22)
    for _ in range(24):
        if contrast(dark, bg) >= 4.5:
            break
        dark = _mix(dark, _BLACK, 0.08)

    soft = _mix(rgb, _WHITE, 0.92)              # подложка активного пункта меню
    line = _mix(rgb, _WHITE, 0.78)              # кромка подложки

    # ⚠️ Установка, которая ничего не выбирала, обязана выглядеть БАЙТ В БАЙТ
    # как до появления темы. Расчёт даёт для #0E9F8A оттенок #0B7C6C вместо
    # шипящегося #0B7E6D — на глаз одно и то же, но «выпустили тему, и у всех
    # поехал цвет» не та новость, которую хочется выяснять по звонку клиники.
    if to_hex(rgb) == DEFAULT_PRIMARY:
        dark, soft, line = (0x0B, 0x7E, 0x6D), (0xEA, 0xFB, 0xF5), (0xCC, 0xF0, 0xE7)

    r, g, b = rgb

    # Чем писать НА фирменном фоне (кнопка, аватар). Порог 3.0, а не 4.5:
    # сегодняшний #0E9F8A даёт с белым 3.3, и требование 4.5 перекрасило бы
    # текст кнопки у всех, кто ничего не выбирал. Это ЗАЩИТА от нечитаемого
    # светлого выбора, а не заявка на соответствие AA.
    on = _WHITE if contrast(_WHITE, rgb) >= 3.0 else _TEXT_DARK

    return {
        "--teal": to_hex(rgb),
        "--teal-d": to_hex(dark),
        "--teal-soft": to_hex(soft),
        "--teal-line": to_hex(line),
        "--teal-ring": f"rgba({r},{g},{b},.12)",     # кольцо фокуса
        "--teal-glow": f"rgba({r},{g},{b},.26)",     # свечение фирменной кнопки
        "--on-teal": to_hex(on),
    }


# ---------- что выбрала клиника ----------

def current() -> dict:
    """Тема из `clinic.json`, уже приведённая к допустимым значениям.

    Читается из `eng.CONFIG` при каждом обращении, а не запоминается: настройки
    применяются на лету (`apply_config`), и запомненная тема пережила бы
    сохранение — «сохранил, а цвет прежний» на пустом месте."""
    raw = eng.CONFIG.get("theme") or {}
    if not isinstance(raw, dict):
        raw = {}
    rgb = parse_hex(raw.get("primary"))
    style = raw.get("style")
    logo = raw.get("logo")
    return {
        "primary": to_hex(rgb) if rgb else DEFAULT_PRIMARY,
        "style": style if style in STYLES else DEFAULT_STYLE,
        "logo": logo if logo in LOGO_NAMES.values() else None,
    }


def vars_css() -> str:
    """Переопределение переменных одной строкой — для `<style>` в шапке.

    Тема НЕ переписывает `panel.css`: файл вшит в exe (только чтение), отдаётся
    с вечным кешем и общий для всех клиник. Меняется здесь ровно то, что
    клиника выбрала, и приезжает это ПОСЛЕ ссылки на таблицу — потому и
    перебивает её."""
    th = current()
    values = dict(STYLES[th["style"]])
    values.update(palette(th["primary"], th["style"]))
    body = "".join(f"{k}:{v};" for k, v in values.items())
    return ":root{" + body + "}"


def accent() -> str:
    """Фирменный цвет для страниц со СВОЕЙ вёрсткой — вход, установка PIN,
    экраны обновления, печатные бланки. У них нет `panel.css` намеренно (вход
    обязан открываться, даже если статика не отдалась), поэтому цвет им
    подставляется значением, а не переменной."""
    return current()["primary"]


def accent_dark() -> str:
    th = current()
    return palette(th["primary"], th["style"])["--teal-d"]


def on_accent() -> str:
    th = current()
    return palette(th["primary"], th["style"])["--on-teal"]


def paint(css: str) -> str:
    """Подставить цвет клиники в таблицу стилей печатного бланка.

    Бланки собираются из констант уровня модуля, а цвет меняется на лету —
    поэтому в константе стоит заполнитель, а не значение: посчитать его при
    импорте значит навсегда запомнить тот цвет, который был при старте."""
    return css.replace("__ACCENT__", accent()).replace("__ON__", on_accent())


def print_logo(cls: str = "clogo") -> str:
    """Логотип клиники для шапки печатного бланка — или пусто.

    ⚠️ Сюда не приходит ничего от пользователя: адрес собирает logo_url() из
    двух разрешённых имён файла, поэтому строка безопасна для вставки как есть.
    """
    url = logo_url()
    return f"<img class='{cls}' src='{url}' alt=''>" if url else ""


# Печатный бланк идёт на бумагу, поэтому размер логотипа задан в МИЛЛИМЕТРАХ:
# пиксели на печати зависят от разрешения драйвера, и логотип, аккуратный на
# экране, вылезал бы на треть листа у одного принтера и терялся у другого.
PRINT_LOGO_CSS = " .clogo{max-height:16mm;max-width:45mm;object-fit:contain}"


# ---------- логотип ----------

# Только растр и только два формата. ⛔ SVG не принимается НИКОГДА: это XML со
# скриптами внутри, и отданный как image/svg+xml он исполняется в контексте
# страницы — тот же класс дыры, что нашло ревью 08-08 в подсказке зуба, только
# без единой строки нашего кода. PDF и ICO не нужны: логотип показывается на
# экране и печатается, для обоих хватает PNG.
LOGO_NAMES = {"png": "clinic-logo.png", "jpg": "clinic-logo.jpg"}
LOGO_MAX = 2 * 1024 * 1024
_SIGNATURES = ((b"\x89PNG\r\n\x1a\n", "png"), (b"\xff\xd8\xff", "jpg"))
_LOGO_MIME = {"png": "image/png", "jpg": "image/jpeg"}


def sniff(data: bytes) -> str | None:
    """Формат по СИГНАТУРЕ файла, а не по расширению.

    ⭐ Прайор из карты: загрузка документов пациента принимает любое расширение,
    и защитой там служит белый список на ОТКРЫТИЕ. Здесь открывать будет
    браузер, и он смотрит в содержимое, а не в имя, — значит и проверять надо
    содержимое. `logo.png`, внутри которого `<svg onload=…>`, отвергается."""
    for sig, kind in _SIGNATURES:
        if data.startswith(sig):
            return kind
    return None


def logo_dir() -> pathlib.Path:
    """Рядом с `clinic.json` — там же, где остальной профиль клиники.

    Значит: переживает обновление программы (установщик не трогает папку
    данных), уезжает вместе с клиникой при переносе на новый ПК и не зависит от
    издания — в облаке `$CLINIC_CONFIG` показывает на смонтированный том."""
    return eng.config_path().parent


def logo_path() -> pathlib.Path | None:
    name = current()["logo"]
    if not name:
        return None
    p = logo_dir() / name
    return p if p.exists() else None


def logo_url() -> str | None:
    """Адрес с отпечатком файла в хвосте: логотип отдаётся с длинным кешем, и
    без этого замена картинки не доехала бы до уже открытых вкладок."""
    p = logo_path()
    if p is None:
        return None
    try:
        stamp = int(p.stat().st_mtime)
    except OSError:
        return None
    return f"/clinic-logo?v={stamp}"


def logo_mime(name: str) -> str:
    return _LOGO_MIME["jpg" if name.endswith(".jpg") else "png"]


def save_logo(data: bytes) -> str:
    """Записать логотип, вернуть имя файла. `ValueError` — если это не картинка.

    Старый файл другого формата удаляется: иначе после замены PNG на JPEG на
    диске остались бы оба, и `clinic.json` указывал бы на один, а второй лежал
    бы мусором до конца жизни установки."""
    if len(data) > LOGO_MAX:
        raise ValueError("logo too big")
    kind = sniff(data)
    if kind is None:
        raise ValueError("not an image")
    name = LOGO_NAMES[kind]
    d = logo_dir()
    d.mkdir(parents=True, exist_ok=True)
    tmp = d / (name + ".tmp")
    tmp.write_bytes(data)
    tmp.replace(d / name)           # атомарно, как и запись профиля
    for other in LOGO_NAMES.values():
        if other != name:
            (d / other).unlink(missing_ok=True)
    return name


def clear_logo() -> None:
    for name in LOGO_NAMES.values():
        (logo_dir() / name).unlink(missing_ok=True)
