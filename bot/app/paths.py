"""Где что лежит. ЕДИНСТВЕННОЕ место в пакете, которое это знает.

Зачем отдельный модуль. Раньше каждый, кому нужен был файл, писал
`Path(__file__).parent / "…"` у себя — то есть привязывался к тому, где лежит
ОН САМ. Пока весь код жил в трёх файлах рядом, это работало. Но стоит модулю
переехать в подпапку (`app/modules/patients/`), и такой путь уезжает вместе с
ним: `clinic.json` не находится, `engine` падает на импорте, программа не
стартует вовсе. Причём только собранная: из исходников `$CLINIC_CONFIG` задан
и до последнего кандидата дело не доходит, так что поломка ждала бы клинику
после установки.

Теперь якорь один и он в корне пакета. Файлы внутри пакета могут переезжать
куда угодно — путь к ресурсам считается отсюда.

⚠️ Сам этот модуль обязан лежать в корне `app/`. Переносить его в подпапку —
значит вернуть ту же проблему, только в одном экземпляре.
"""
from __future__ import annotations

import os
import pathlib
import sys

# Корень пакета. В обычном запуске — папка `app/`. В onefile-сборке PyInstaller
# распаковывает вшитые файлы во временный каталог `sys._MEIPASS`, а
# Build-Desktop.ps1 кладёт их туда с префиксом `app` (--add-data "…;app"), —
# поэтому в exe корень ресурсов это _MEIPASS/app.
if getattr(sys, "frozen", False) and hasattr(sys, "_MEIPASS"):
    PKG_ROOT = pathlib.Path(sys._MEIPASS) / "app"       # noqa: SLF001
else:
    PKG_ROOT = pathlib.Path(__file__).resolve().parent


def is_frozen() -> bool:
    return bool(getattr(sys, "frozen", False))


def resource(*parts: str) -> pathlib.Path:
    """Файл, ВШИТЫЙ в сборку: демо-профиль клиники, статика, иконки.

    Только для чтения. В exe это распакованная временная папка — она исчезает
    при выходе, и запись туда теряется молча."""
    return PKG_ROOT.joinpath(*parts)


def data_root() -> pathlib.Path | None:
    """Папка КЛИНИКИ: `clinic.json`, `dental.env`, `data\\`, логи.

    ⛔ Больше НЕ «рядом с exe». С переезда в `Program Files` папка программы
    доступна только на чтение, и вычислять место записи от `sys.executable`
    нельзя: у клиники это был бы отказ доступа, а у разработчика — молча
    работающая запись в дерево исходников. Здесь раньше жил `runtime_dir()`,
    и он удалён намеренно, а не переименован: удалённое имя падает на импорте,
    псевдоним с неверным смыслом падает в три часа дня у клиники.

    Значение задаёт ЛАУНЧЕР через `$DENTART_DATA_DIR` — он один знает раскладку
    машины. Нет переменной (облако, прогон, запуск из исходников) — `None`, и
    вызывающий обязан этот случай обработать, как и у `storage._data_dir()`.

    ⛔ Читается только окружение ПРОЦЕССА и никогда `dental.env`: тот лежит
    ВНУТРИ этой самой папки, и ключ в нём — замкнутый круг, который на втором
    запуске разрешился бы в другое место.
    ⚠️ Относительный путь отвергается: он считался бы от текущего каталога,
    а у службы и у ярлыка он разный.
    """
    raw = os.environ.get("DENTART_DATA_DIR", "").strip().strip("\"'")
    if not raw:
        return None
    p = pathlib.Path(raw)
    return p if p.is_absolute() else None


def db_dir() -> pathlib.Path | None:
    """Каталог САМОЙ базы: `dental.db`, `db.key`, `auth.json`, `backups\\`,
    `files\\`.

    ⭐ Считается от `$DATABASE_URL`, а НЕ как `data_root()/"data"`. Два
    определения одного места неминуемо разойдутся — и первым это увидит не
    человек, а `dbkey.state()`, который доложит «шифрование выключено» про
    зашифрованную картотеку, потому что смотрит в папку без `db.key`.

    ⚠️ У настольного издания выполняется `db_dir() == data_root()/"data"`, но
    это следствие того, как лаунчер собирает пути, а не определение. В прогоне
    и в облаке они независимы.
    """
    f = db_file()
    return f.parent if f else None


def db_file() -> pathlib.Path | None:
    """Сам файл базы. ⭐ ЕДИНСТВЕННОЕ место, где разбирается `$DATABASE_URL`.

    Разбирали его в трёх местах (`db.init`, режим восстановления в `main`, и
    здесь), и пока раскладка была одна, три одинаковые строки были безобидны.
    С разделением папок это перестало быть правдой: любая из них, разойдясь с
    остальными, откроет ДРУГОЙ файл — а «другой файл» для SQLite означает не
    ошибку, а пустую новую базу.
    """
    url = os.environ.get("DATABASE_URL", "")
    if not url.startswith("sqlite"):
        return None
    return pathlib.Path(url.split("///", 1)[1])
